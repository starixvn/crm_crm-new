export class CreateForm extends Component {
    constructor(props) {
        super(props);
        this.formik = React.createRef();
        this.dateTimeAndToolPattern = 'Date Time & Tool: \\d{8}\\/\\d{2}:\\d{2}\\D{2}\\/';
        this.systemPattern = 'System ID: (.*)';
        this.state = {
            feedbackDate: new Date(DateTimeService.toShortDateTimeFormat(DateTimeService.toClientDateTime(new Date()))),
            autoGeneratedInit: '',
            collapse: {
                isShowCustomerDetailOption: false,
                isShowDetailsOption: false,
                isVerifyCustomer: false,
                description: false,
                solution: false
            },
            editBlock: {
                isEditDescription: true,
                isEditSolution: true
            },
            communicationToolVal: '',
            subCategoriesOptions: [],
            subProductOptions: [],
            betTypeOptions: [],
            listOfCustomerValid: [],
            listOfCustomer: [],
            countClickRefTicket: 0,
            checkDuplicateDialog: { show: false },
            duplicateFeedbackId: 0,
            customerInfo: {
                title: props.settings.titles[0].id,
                firstName: '',
                lastName: '',
                birthday: '',
                passportNo: '',
                licenseeType: props.settings.licenseeTypes[0].id,
                countryCode: '',
                phoneNumber: '',
                areaCode: '',
                countryCode2: '',
                phoneNumber2: '',
                areaCode2: '',
                countryCode3: '',
                phoneNumber3: '',
                areaCode3: '',
                mobileCountryCode: '',
                mobileAreaCode: '',
                mobilePhoneNumber: '',
                faxCountryCode: '',
                faxAreaCode: '',
                faxNumber: '',
                pic1Name: '',
                pic1PhoneNumber: '',
                pic2Name: '',
                pic2PhoneNumber: '',
                pic3Name: '',
                pic3PhoneNumber: '',
                pic4Name: '',
                pic4PhoneNumber: '',
                skype: '',
                email: '',
                telegram: '',
                weChat: '',
                whatApp: '',
                line: '',
                letstalk: '',
                qq: '',
                zalo: '',
                isOverwriteInfo: false,
                headlineStaffInfoCommunications: [],
                headlineStaffInfoLanguages: [],
                headlineStaffInfoPics: [],
                otherAccountCommunicationInfos: [],
                guestCommunicationInfos: []
            },
            content: {
                autoGenerated: '',
                description: '',
                solution: ''
            },
            checkChattypeMappingDialog: {
                show: false,
                data: []
            },
            headlineInfoPolicy: null
        };
    }
    componentDidMount() {
        getPermission(FunctionKey.HeadlineInfo, true).then(response => {
            this.setState({ headlineInfoPolicy: response });
        });
        const autoGenerated = this.renderAutoGeneratedText();
        this.setState({ content: { ...this.state.content, autoGenerated } });
        if (this.props.customerDetail !== undefined && this.props.customerDetail !== null) {
            const customerInfo = initCustomerInfo(this.props.customerDetail);
            this.setState({ customerInfo });
        }
    }

    handleKeyDownFunc = event => {
        if (event.ctrlKey && event.key === 's') {
            event.preventDefault();
            if(!this.formik.isSubmitting){
                this.formik.submitForm();
            }
        }

        if (event.ctrlKey && event.key === 'e' && this.state.collapse.isVerifyCustomer) {
            const { setFieldValue, values } = this.formik;
            this.handleVerify(event, setFieldValue, values.customerNameInput);
        }
    }

    renderOptions = (name, item) => <option key={item} value={item}>{name}</option>;

    handleChangeFeedbackTime = feedbackDate => {
        this.formik.setFieldValue('feedbackDate', feedbackDate);
        this.setState({ feedbackDate }, () => {
            setTimeout(() => this.updateTimeAndToolPrefix(), 100);
        });
    };

    handleChangeResolutionTime = (resolutionTime) => {
        this.formik.setFieldValue('resolutionTime', resolutionTime);
    };

    handleCommunicationChange = (currentItem, selectedItemsKey, setFieldValue) => {
        setFieldValue('communication', selectedItemsKey);
        const { communicationTools } = this.props.settings;
        let communicationToolVal = '';
        if (selectedItemsKey.split(',').length === communicationTools.length) {
            communicationToolVal = communicationTools[0].name;
        } else if (currentItem !== '' && selectedItemsKey !== '' && currentItem.checked) {
            communicationToolVal = currentItem.name;
        } else if (selectedItemsKey !== '') {
            const firstCommIns = selectedItemsKey.split(',')[0];
            communicationToolVal = communicationTools.filter(x => x.id.toString() === firstCommIns)[0].name;
        }
        this.setState({ communicationToolVal }, () => {
            setTimeout(() => this.updateTimeAndToolPrefix(), 100);
        });
    };

    handleCollapseExpend = section => {
        this.setState(prevState => ({
            collapse: { ...prevState.collapse, [section]: !prevState.collapse[section] }
        }));
    };

    handleEditBlock = (event, section) => {
        event.stopPropagation();
        this.setState(prevState => ({
            editBlock: { ...prevState.editBlock, [section]: !prevState.editBlock[section] }
        }));
    };

    mainCategoriesHandleChange = (currentItem, selectedItemsKey, setFieldValue, values) => {
        if (selectedItemsKey) {
            const tempSubject = getSubjectOnChangeCategories(selectedItemsKey ? selectedItemsKey.split(',') : [],
                values.subject,
                this.props.settings.mainCategories);
            setFieldValue('subject', tempSubject);
            setFieldValue('category', selectedItemsKey);
            const subCategories = this.props.settings.subCategories;
            const selectedMainCategories = selectedItemsKey.split(',');
            const subCategoriesSelectedArr = values.subCategory.length > 0 ? values.subCategory.split(',') : [];
            const findSubByMain = getSubCategories(selectedMainCategories, subCategories, subCategoriesSelectedArr, false);
            this.setState({ subCategoriesOptions: findSubByMain });
        } else {
            this.setState({
                subCategoriesOptions: []
            });
            setFieldValue('category', '');
            setFieldValue('subCategory', '');
            setFieldValue('subject', '');
        }
    };

    productHandleChange = (currentItem, selectedItemsKey, setFieldValue, subProductSelected) => {
        setFieldValue('product', selectedItemsKey);
        if (selectedItemsKey) {
            const subProducts = this.props.settings.subProducts;
            const selectedProduct = selectedItemsKey.split(',');
            const subProductSelectedArr = subProductSelected.length > 0 ? subProductSelected.split(',') : [];
            const findSubProductByProduct = getSubProducts(selectedProduct, subProducts, subProductSelectedArr, false);
            this.setState({ subProductOptions: findSubProductByProduct });
        } else {
            this.setState({
                subProductOptions: [],
                betTypeOptions: []
            });
            setFieldValue('subProduct', '');
            setFieldValue('betType', '');
        }
    };

    subProductHandleChange = (currentItem, selectedItemsKey, setFieldValue, betTypesSelected) => {
        setFieldValue('subProduct', selectedItemsKey);
        if (selectedItemsKey) {
            const betTypes = this.props.settings.bettypes;
            const selectedSubProducts = selectedItemsKey.split(',');
            const betTypeSelectedArr = betTypesSelected.length > 0 ? betTypesSelected.split(',') : [];
            const findBetTypeBySubProduct = getBetTypes(selectedSubProducts, betTypes, betTypeSelectedArr, false);
            this.setState({ betTypeOptions: findBetTypeBySubProduct });
        } else {
            this.setState({
                betTypeOptions: []
            });
            setFieldValue('betType', '');
        }
    };

    handleVerify = (event, setFieldValue, value) => {
        event.preventDefault();
        if (value === '') {
            return;
        }
        const regex1 = new RegExp(/,\s+/g);
        const regex2 = new RegExp(/^,+|,+$/g);
        const regex3 = new RegExp(/,{2,}/g);
        const regex4 = new RegExp(/ /g);

        const customersInput = value.trim().replace(regex1, ',') // NOSONAR
            .replace(regex2, '') // NOSONAR
            .replace(regex3, ',') // NOSONAR
            .replace(regex4, ','); // NOSONAR

        const isValid = customersInput.split(',').filter(value => value.length > 50).length === 0;

        if (isValid) {
            this.props.setAddFeedback(null);
            this.props.verifyUserName({ Username: customersInput }).then(data => {
                let customers = [...this.state.listOfCustomer, ...data];
                customers = customers.filter((v, i, a) => a.findIndex(t => t.custId === v.custId && t.val === v.val) === i);
                this.setState({
                    listOfCustomer: customers,
                    listOfCustomerValid: customers.filter(item => item.custId !== 0 && item.isAuthorized)
                }, () => {
                    setTimeout(() => this.updateTimeAndToolPrefix(), 100);
                });
            });
            setFieldValue('isVerifiedCustomers', true);
        } else {
            toast.error('The customer name must not be longer than 50 characters!');
        }
        setFieldValue('customerNameInput', '');
    };

    handleReVerifyInactiveAndConfirm = (values, userNames) => {
        this.props.verifyUserName({ Username: userNames }).then(data => {
            const inactiveCustomers = data.filter(customer => !customer.isSiteActive && customer.custId !== 0 && customer.isLicensee);
            this.setState({ listOfCustomer: data });
            if (inactiveCustomers.length > 0) {
                this.formik.setSubmitting(false);
                const inactiveUserName = inactiveCustomers.map(x => x.val).join(',');
                const message = LangHelper.getResource('ErrorMessageInactiveSiteRelate') + inactiveUserName;
                this.props.setAddFeedback({ isSuccessful: false, message });
            } else {
                this.props.setAddFeedback(null);
                this.handleConfirm(values);
            }
        });
    };

    onPasteCustomerHandler = (event, customers, setFieldValue) => {
        const customer = customers.trim();
        const items = (event.clipboardData || window.clipboardData).getData('text').replace(/ /g, ',')
            .replace(/\r\n/g, ',').replace(/\n/g, ',').replace(/\t/g, ',').split(',').filter(item => item !== '');
        setTimeout(() => {
            const customersInput = (customer.length > 0 ? customer + ',' : '').concat(items.join(','));
            setFieldValue('customerNameInput', customersInput);
        }, 100);
    };

    deleteCustomerVerify = id => {
        const listOfCustomer = this.state.listOfCustomer.filter(item => item.custId !== id);
        const listOfCustomerValid = this.state.listOfCustomerValid.filter(item => item.custId !== id && item.isAuthorized);
        this.setState({
            listOfCustomer,
            listOfCustomerValid
        }, () => {
            setTimeout(() => this.updateTimeAndToolPrefix(), 100);
        });
    };

    handleGetFeedbackSubjectTemplates = Site.debounce(searchText => {
        if (searchText.length >= 2) {
            this.props.getFeedbackSubjectTemplates(searchText);
        } else {
            this.props.setFeedbackSubjectTemplates([]);
        }
    });

    handleCloseConfirmCreateGuestDialog = () => {
        this.formik.setSubmitting(false);
        this.props.setConfirmCreateGuestDialog({ show: false });
    };

    handleChangeRefTicket = (e, setFieldValue) => {
        const value = e.target.value > 19 ? e.target.value.slice(0, 19) : e.target.value;
        setFieldValue('ticketRefInput', value);
    };

    onPasteRefTicketHandler = event => {
        if (event.clipboardData.getData('Text').match(/[^\d]/)) {
            event.preventDefault();
        }
    };

    validateRefInput = event => {
        if ([8, 46, 37, 39, 35, 36].includes(event.which)) {
            return;
        }

        if (!event.ctrlKey && !event.key.match(/^\d+$/)) {
            event.preventDefault();
        }
    }

    handleClickFillEvent = (ticketRefInput, setFieldValue) => {
        Site.blockUI();
        const description = this.state.content.description;
        const autoGenerated = '<span style=\"color: rgb(255, 0, 0);\">This is an auto-generated entry.</span>';
        const colorGenerated = 'color: rgb(255, 0, 0)';
        this.props.getTicketInfoByRef({ refno: ticketRefInput }).then(data => {
            Site.unblockUI();
            setFieldValue('ticketRefInput', '');
            if (!data) {
                return;
            } else if (data.errorCode !== '0') {
                this.props.setAddFeedback({ isSuccessful: false, message: data.description });
            } else {
                let descriptionText = '';
                this.props.setAddFeedback(null);
                const isFirstInputAndHasData = description.length > 0 && this.state.countClickRefTicket === 0;
                const isNotFirstInputAndRemoveData = this.state.countClickRefTicket !== 0 && !description.includes(colorGenerated);
                if (isFirstInputAndHasData || isNotFirstInputAndRemoveData) {
                    descriptionText = `${data.description} <br> ${description}`;
                } else if (this.state.countClickRefTicket === 0) {
                    descriptionText = data.description;
                } else {
                    const removeAutoGenerate = data.description.replace(autoGenerated, '');
                    descriptionText = description + removeAutoGenerate;
                }
                this.handleChangeContent('description', descriptionText);
            }

            this.setState(prevState => ({
                countClickRefTicket: prevState.countClickRefTicket + 1
            }));
        });
    };

    generateCustomerPrefix = () => {
        const customerJoin = this.getCustomerVal();
        return 'System ID: ' + customerJoin;
    };

    getCustomerVal = () => {
        const relatedCustomers = this.state.listOfCustomerValid;
        let customerJoin = '';
        if (relatedCustomers.length > 0) {
            customerJoin = relatedCustomers.map(cust => cust.val).join(', ');
        }
        return customerJoin;
    };

    renderAutoGeneratedText = () => {
        const lastedCommunicationVal = this.state.communicationToolVal !== '' ? this.state.communicationToolVal : 'N/A';
        const generateTime = generateTimeAndToolPrefix(this.state.feedbackDate, lastedCommunicationVal);
        const generateCustomer = this.generateCustomerPrefix();
        return `${generateTime}\n${generateCustomer}`;
    };

    updateTimeAndToolPrefix = () => {
        const lastedCommunicationVal = this.state.communicationToolVal !== '' ? this.state.communicationToolVal : 'N/A';
        const customerVal = this.getCustomerVal();
        let oldCustVal = '';
        const newTimeAndToolPrefix = generateTimeAndToolPrefix(
            this.state.feedbackDate, lastedCommunicationVal);
        const autoGenerated = this.state.content.autoGenerated;
        let autoGeneratedReplace = autoGenerated;
        const oldTimeAndToolPrefix = this.matchTimeAndToolPrefix(autoGenerated);
        const match = autoGenerated.match(new RegExp(this.systemPattern));
        if (match !== null) {
            oldCustVal = match[1];
        }

        if (oldCustVal.trim().length > 0) {
            autoGeneratedReplace = autoGenerated.replace(oldCustVal, customerVal);
        } else {
            autoGeneratedReplace = autoGeneratedReplace.replace(/System ID:.*/, 'System ID: '+ customerVal);
        }

        const autoGeneratedText = oldTimeAndToolPrefix !== ''
            ? `${autoGeneratedReplace.replace(oldTimeAndToolPrefix, newTimeAndToolPrefix)}`
            : `${newTimeAndToolPrefix}\n${autoGeneratedReplace}`;
        this.handleChangeContent('autoGenerated', autoGeneratedText);
    };

    matchTimeAndToolPrefix = (autoGeneratedText = '') => {
        const communicationTools = [...this.props.settings.communicationTools];
        communicationTools.unshift({ name: 'N/A' });
        let result = '', match;
        for (let i = 0; i < communicationTools.length; i++) {
            const tool = communicationTools[i];
            match = autoGeneratedText.match(new RegExp(this.dateTimeAndToolPattern + tool.name));
            if (match !== null) {
                result = match[0];
                break;
            }
        }

        if (result === '') {
            match = autoGeneratedText.match(new RegExp(this.dateTimeAndToolPattern));
            if (match !== null) {
                result = match[0];
            }
        }

        return result;
    };

    handleChangeContent = (name, value) => {
        this.setState({ content: { ...this.state.content, [name]: value } });
    };

    handleChangeCustomerInfo = event => {
        this.setState({ customerInfo: { ...this.state.customerInfo, [event.target.name]: event.target.value } });
    };

    handleChangeValueInfo = (name, value) => {
        this.setState({ customerInfo: { ...this.state.customerInfo, [name]: value } });
    };

    renderIdentityInformation = (values, errors, touched, handleChange, setFieldValue) => {
        const { customerDetail } = this.props;
        const { isShowCustomerDetailOption } = this.state.collapse;
        const isCollapse = customerDetail === null ? !isShowCustomerDetailOption : isShowCustomerDetailOption;
        const borderStyle = isCollapse ? BorderStyle.bottom : '';
        return (
            <div className={`panel-group ${BorderStyle.bottom}`}>
                {
                    customerDetail === null ?
                        <Form.Group as={Row} className={`title align-items-center`}
                            aria-controls="collapse-expand-identity"
                            aria-expanded={isCollapse}
                        >
                            <Form.Label column sm="1" md="2" className='required'
                                onClick={() => this.handleCollapseExpend('isShowCustomerDetailOption')}
                            >
                                {LangHelper.getResource('IdentityInformation')}
                            </Form.Label>
                            {
                                <Col sm="2" md="2">
                                    <Form.Control type="text" size="sm" value={values.identityInformation}
                                        name="identityInformation" id="identityInformation"
                                        className="shadow-none" autoComplete="on"
                                        isInvalid={touched.identityInformation && errors.identityInformation}
                                        onChange={handleChange}
                                    />
                                </Col>
                            }
                        </Form.Group> :
                        <Form.Group as={Row} className={`title ${borderStyle}`}
                            aria-controls="collapse-expand-identity"
                            aria-expanded={isCollapse}
                            onClick={() => this.handleCollapseExpend('isShowCustomerDetailOption')}
                        >
                            <Form.Label column sm="2" md="2" className='username'>{customerDetail.username}</Form.Label>
                        </Form.Group>
                }
                <Collapse in={isCollapse}>
                    <div id="collapse-expand-show-identity">
                        {
                            <CustomerInfo
                                isGuest={this.props.isGuest}
                                customerDetail={customerDetail}
                                settingCommunicationTool={this.props.settingCommunicationTool}
                                customerInfo={this.state.customerInfo}
                                errors={errors} touched={touched} setFieldValue={setFieldValue}
                                handleChange={this.handleChangeCustomerInfo}
                                handleChangeValueInfo={this.handleChangeValueInfo}
                                settings={this.props.settings}
                                renderOptions={this.renderOptions}
                            />
                        }
                    </div>
                </Collapse>
            </div>
        );
    };

    renderDetails = (values, errors, touched, handleChange, setFieldValue) => {
        const collapse = this.state.collapse;
        const customerDetail = this.props.customerDetail;
        const isInValidSolution = touched.solution && errors.solution;
        const isInValidDescription= touched.description && errors.description;
        return (
            <div>
                <div className={`panel-group ${BorderStyle.bottom}`}>
                    <Form.Group as={Row} className={`title`}
                        onClick={() => this.handleCollapseExpend('isShowDetailsOption')}
                        aria-controls="collapse-expand-detail"
                        aria-expanded={!collapse.isShowDetailsOption}
                    >
                        <Form.Label column sm="2" md="2" className="required">
                            {LangHelper.getResource('Details')}
                        </Form.Label>
                    </Form.Group>
                </div>
                <Collapse in={!collapse.isShowDetailsOption}>
                    <div className={`panel-group ${BorderStyle.bottom}`} id="collapse-expand-show-detail">
                        <Detail
                            settings={this.props.settings} customerDetail={customerDetail} handleChange={handleChange}
                            values={values} errors={errors} touched={touched} setFieldValue={setFieldValue} handleChangeFeedbackTime={this.handleChangeFeedbackTime}
                            handleChangeResolutionTime={this.handleChangeResolutionTime} handleCommunicationChange={this.handleCommunicationChange}
                            subCategoriesOptions={this.state.subCategoriesOptions} subProductOptions={this.state.subProductOptions}
                            betTypeOptions={this.state.betTypeOptions} renderOptions={this.renderOptions} mainCategoriesHandleChange={this.mainCategoriesHandleChange}
                            productHandleChange={this.productHandleChange} subProductHandleChange={this.subProductHandleChange}
                        />
                        {this.renderVerifyCustomer(values, handleChange, setFieldValue)}
                        <VerifyCustomer listOfCustomers={this.state.listOfCustomer} onClick={this.deleteCustomerVerify} isBigColumnSize/>
                        {this.renderRefTicket(values, setFieldValue)}
                        <Form.Group as={Row} className="pt-1 pb-2 mt-1">
                            <Col sm="3" md="2">
                                <Form.Label className="required col-subject-width form-label col-form-label">
                                    {LangHelper.getResource('Subject')}
                                </Form.Label>
                            </Col>
                            <Col sm="9" md="10" className="subject-auto-complete-container">
                                <AutoComplete
                                    options={this.props.feedbackSubjectTemplates} displayField="subject" value={values.subject}
                                    onChange={value => setFieldValue('subject', value.subject || value)} isInvalid={touched.subject && errors.subject}
                                    onInputChange={searchText => this.handleGetFeedbackSubjectTemplates(searchText)}
                                />
                            </Col>
                        </Form.Group>
                        {
                            customerDetail === null &&
                            <Content
                                editBlock={this.state.editBlock} collapse={this.state.collapse} isInValidSolution={isInValidSolution}
                                content={this.state.content} handleEditBlock={this.handleEditBlock} isInValidDescription={isInValidDescription}
                                handleCollapseExpend={this.handleCollapseExpend} handleChangeContent={this.handleChangeContent}
                            />
                        }
                    </div>
                </Collapse >
                {
                    customerDetail !== null &&
                    <Content
                        editBlock={this.state.editBlock} collapse={this.state.collapse} isInValidSolution={touched.solution && errors.solution}
                        content={this.state.content} handleEditBlock={this.handleEditBlock} isInValidDescription={touched.description && errors.description}
                        handleCollapseExpend={this.handleCollapseExpend} handleChangeContent={this.handleChangeContent}
                    />
                }
            </div>
        );
    };

    renderVerifyCustomer = (values, handleChange, setFieldValue) => {
        return (
            <Form.Group as={Row} className="pt-1 pb-2">
                <Col sm="2" md="2">
                    <OverlayTrigger placement="bottom-start" overlay={
                        <Tooltip id={'add-feedback-tooltip-customers'}>
                            {LangHelper.getResource('MultipleCustomersTooltip')}
                        </Tooltip>}
                    >
                        <span className="fa fa-question-circle-o" />
                    </OverlayTrigger>
                    <Form.Check type="checkbox" id="check-box-verify" label={LangHelper.getResource('IsRelatedToCustomer')}
                        htmlFor="check-box-verify" checked={this.state.collapse.isVerifyCustomer}
                        onChange={() => this.handleCollapseExpend('isVerifyCustomer')}
                    />
                </Col>
                <Col sm="10" md="10">
                    <Row>
                        <Col sm="9" md="9">
                            <Form.Control type="text" size="sm" value={values.customerNameInput} disabled={!this.state.collapse.isVerifyCustomer}
                                name="customerNameInput" className="shadow-none" autoComplete="off" onChange={handleChange}
                                onPaste={event => this.onPasteCustomerHandler(event, values.customerNameInput, setFieldValue)} />
                        </Col>
                        <Col sm="1" md="1">
                            <Button name="isVerifiedCustomers" id="isVerifiedCustomers" className="w-100" type="submit" variant="primary"
                                disabled={!this.state.collapse.isVerifyCustomer}
                                size="sm" onClick={event => this.handleVerify(event, setFieldValue, values.customerNameInput)}>
                                <UnderlineButton.verifyButton/>
                            </Button>
                        </Col>
                    </Row>
                </Col>
            </Form.Group>
        );
    };

    renderRefTicket = (values, setFieldValue) => {
        return (
            <Form.Group as={Row}>
                <Col sm="3" md="2">
                    <Form.Label htmlFor="ticketRefNo">{LangHelper.getResource('TicketRefNo')}</Form.Label>
                    <OverlayTrigger placement="auto" overlay={
                        <Tooltip id='add-feedback-tooltip-ref-ticket'>
                            {LangHelper.getResource('TooltipRefTicket') + this.props.balanceUpday}
                        </Tooltip>}
                    >
                        <span className="fa fa-question-circle-o" />
                    </OverlayTrigger>
                </Col>
                <Col sm="9" md="10">
                    <Row>
                        <Col sm="5" md="5">
                            <Form.Control type="number" size="sm"
                                value={values.ticketRefInput}
                                onKeyDown={event => this.validateRefInput(event)}
                                onPaste={event => this.onPasteRefTicketHandler(event)}
                                id="refNo" name="refNo" className="shadow-none" autoComplete="off"
                                onChange={e => this.handleChangeRefTicket(e, setFieldValue)}
                            />
                        </Col>
                        <div>
                            <Button disabled={values.ticketRefInput === ''} className="w-100" onClick={() => this.handleClickFillEvent(values.ticketRefInput, setFieldValue)}>
                                {LangHelper.getResource('FillEventDetails')}
                            </Button>
                        </div>
                    </Row>
                </Col>
            </Form.Group>
        );
    };

    renderComfirmChatTypeMapping(rating) {
        return <>
            <ReminderRating value={rating}/>
            <div className="confirm-headline">{LangHelper.getResource('ConfirmContentHeadlineCommunicationInfo')}</div>
            {
                this.state.checkChattypeMappingDialog.data.map(item => {
                    return (<>
                        <div>
                            <span>{`${item[0].picInfo}: `}</span>
                            {
                                this.renderValueChatTypeMapping(item)
                            }
                        </div>
                    </>);
                })
            }
        </>
    }

    renderValueChatTypeMapping(data) {
        let chatTypeMapping = [];
        data.map((comPic, indexPic) => {
            chatTypeMapping.push(<>
                {indexPic !== 0 && <span>{', '}</span>}
                <strong>{comPic.communicationValue}</strong>
                <span>{` (${comPic.communicationTool})`}</span>
            </>);
        })
        return chatTypeMapping;
    }

    renderForm = ({
        values,
        errors,
        touched,
        handleChange,
        handleSubmit,
        setFieldValue,
        isSubmitting
    }) => {
        return (
            <Form noValidate onSubmit={handleSubmit} action="javascript:void(0)" className="form-pannel">
                <WithHotKey handleKeyDownFunc={this.handleKeyDownFunc} isDocumentHandle />
                <FormikErrorMessage isSubmitting={isSubmitting} touched={touched} errors={errors} fieldNames={Object.keys(values)} />
                {
                    this.props.addFeedbackResult &&
                    <ResponseMessage isSuccessful={this.props.addFeedbackResult.isSuccessful}
                        message={this.props.addFeedbackResult.message || LangHelper.getResource('AddFeedbackSuccessfully')} />
                }
                {
                    this.renderIdentityInformation(values, errors, touched, handleChange, setFieldValue)
                }
                {
                    this.renderDetails(values, errors, touched, handleChange, setFieldValue)
                }
                {
                    this.props.confirmCreateGuestDialog.show &&
                    <SweetModalDialog size="lg"
                        title={LangHelper.getResource('Confirmation')}
                        contents={
                            <>
                                <ReminderRating value={values.rating}/>
                                <div dangerouslySetInnerHTML={{ __html: this.props.confirmCreateGuestDialog.confirmMessage }} />
                                {
                                    this.state.customerInfo.isOverwriteInfo &&
                                    <div>
                                        <strong>{`Attention: `}</strong>
                                        <span >You have checked to</span>
                                        <strong>{` Overwrite `}</strong>
                                        <span >the current account details! Account and communication information will be updated accordingly.</span>
                                    </div>
                                }
                            </>
                        }
                        buttons={[
                            <Button variant="primary" size="sm" disabled={isSubmitting} onClick={this.handleCreateFeedback}>
                                {LangHelper.getResource('OK')}
                            </Button>,
                            <Button variant="primary" size="sm" onClick={this.handleCloseConfirmCreateGuestDialog}>
                                {LangHelper.getResource('Cancel')}
                            </Button>]}
                        onClose={this.handleCloseConfirmCreateGuestDialog}
                    />
                }
                {
                    this.state.checkDuplicateDialog.show &&
                    <SweetModalDialog size="lg"
                        title={LangHelper.getResource('Warning')}
                        contents={
                            <>
                                <ReminderRating value={values.rating}/>
                                <div>{`This customer has a similar log with running number ${this.state.duplicateFeedbackId}. Do you want to create this log?`}</div>
                            </>
                        }
                        buttons={[
                            <Button variant="primary" size="sm" disabled={isSubmitting} onClick={this.checkChattypeMapping}>
                                {LangHelper.getResource('OK')}
                            </Button>,
                            <Button variant="primary" size="sm" onClick={this.handleCloseCheckDuplicateDialog}>
                                {LangHelper.getResource('Cancel')}
                            </Button>
                        ]}
                        onClose={this.handleCloseCheckDuplicateDialog} />
                }
                {
                    this.state.checkChattypeMappingDialog.show &&
                    <ConfirmPopup
                        className='confirm-headline-modal'
                        title={LangHelper.getResource('ConfirmHeadlineCommunicationInfo')}
                        content={this.renderComfirmChatTypeMapping(values.rating)}
                        size='lg'
                        onSubmit={() => {
                                this.editHeadlineCommunicationPic();
                                this.createFeedback();
                            }
                        }
                        onClose={() => { this.setState({ checkChattypeMappingDialog: { show: false, data: [] } }); } }
                    />
                }
                <Form.Group as={Row} className="mt-3">
                    <Col>
                        <Button type="submit" variant="primary" size="sm" disabled={isSubmitting}>
                            <UnderlineButton.saveButton />
                        </Button>
                    </Col>
                </Form.Group>
            </Form>
        );
    };

    handleSubmit = values => {
        if (!isHavePermissionOnSite()) {
            this.formik.setSubmitting(false);
            return;
        }
        const userNameInput = this.state.listOfCustomerValid.map(x => x.val).join(',');
        if (userNameInput.length > 0) {
            this.handleReVerifyInactiveAndConfirm(values, userNameInput);
        } else {
            this.handleConfirm(values);
        }
    };

    handleConfirm = values => {
        const params = getParams(values, this.props.customerDetail, this.props.settings, this.state);
        const specialChars = ['<', '>', '#', '&'];
        const inValidName = this.props.customerDetail === null && specialChars.filter(x => params.UserName.indexOf(x) >= 0).length > 0;
        if (inValidName) {
            params.UserName = params.UserName.replace(/<|>|#|&/g, '');
            this.confirmCreateAddGuestFeedback(params, LangHelper.getResource('ConfirmAddGuestFeedbackSpecialChar'));
        } else {
            this.confirmCreateAddGuestFeedback(params, LangHelper.getResource('ConfirmAddGuestFeedback'));
        }
    };

    confirmCreateAddGuestFeedback = (params, confirmMessage) => {
        this.formik.setSubmitting(false);
        this.props.setConfirmCreateGuestDialog({
            show: true,
            params,
            confirmMessage
        });
    };

    handleCheckDuplicateFeedback = async params => {
        const url = 'Feedback/CheckFeedbackDuplication';
        Site.blockUI();
        await DataService.postDataAsync(url, {
            customerId: params.CustId,
            categories: params.Categories,
            startTime: params.FeedbackDate
        }).then(response => {
            this.setState({ duplicateFeedbackId: response.data }, async () => {
                if (response.data === 0) {
                    await this.checkCustomerExistsOnCRM();
                }else {
                    this.setState({ checkDuplicateDialog: { show: true } });
                }
            });
        }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);
    };

    handleCloseCheckDuplicateDialog = () => {
        this.formik.setSubmitting(false);
        this.setState({ checkDuplicateDialog: { show: false } });
        this.props.setConfirmCreateGuestDialog({ show: false });
    };

    handleCreateFeedback = async () => {
        const { params } = this.props.confirmCreateGuestDialog;
        if (this.props.customerDetail !== null) {            
            this.handleCheckDuplicateFeedback(params);                
        } else {
            await this.checkChattypeMapping();
        }
    };

    validateChattypeMappingPic = async () => {
        let validResult = null;
        if (this.props.customerDetail?.isGroupHeadLine && this.state.headlineInfoPolicy === Policy.Host && this.state.customerInfo.isOverwriteInfo) {
            const { headlineStaffInfoCommunications, headlineStaffInfoPics } = this.state.customerInfo;
            const communications = getHeadlineCommunicationInfoPIC(headlineStaffInfoCommunications, headlineStaffInfoPics);
            const params = communications.map(pic => {
                return {
                    picId: pic.picId,
                    picCommunicationTools: pic.picCommunicationTools.map(com => { return { type: com.picCommunicationId, value: com.picCommunicationValue }; })
                };
            });
            Site.blockUI();
            const url = Site.resolveClientUrl('AccountDetail/ValidateEditPic');
            await DataService.postDataAsync(url, params).then(async response => {
                validResult = response.data;
                if (validResult.length === 0) {
                    await this.editHeadlineCommunicationPic();
                }
            }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);
        }
        return validResult;
    }

    getPicChangeInformation() {
        const headlineCommunicationInfo = getHeadlineCommunicationInfo(this.state.customerInfo);
        const originalHeadlineCommunicationInfo = getHeadlineCommunicationInfo(this.props.customerDetail);
        let headlineChangeCommunicationInfo = [];
        headlineCommunicationInfo.map((item, index) => {
            if (JSON.stringify(item).toString() !== JSON.stringify(originalHeadlineCommunicationInfo[index]).toString()) {
                headlineChangeCommunicationInfo.push(item);
            }
        });
        return headlineChangeCommunicationInfo;
    }

    getParamEdit() {
        const headlineChangeCommunicationInfo = this.getPicChangeInformation();
        const params = headlineChangeCommunicationInfo.map(pic => {
            let picCommunicationTools = [];
            pic.picCommunicationTools.map((picCom, indexCom) => {
                const index = pic.picCommunicationTools.findIndex(item => item.type === picCom.type);
                if (index >= 0 && index !== indexCom) {
                    const newValue = picCommunicationTools[index].value.concat(', ', picCom.value);
                    picCommunicationTools[index].value = newValue;
                } else {
                    picCommunicationTools.push({ ...picCom });
                }
            })

            return {
                country: pic.country,
                language: pic.language,
                picId: pic.picId,
                picName: pic.picName,
                picType: pic.picType,
                role: pic.role,
                picCommunicationTools: picCommunicationTools,
                remark: ''
            };
        });
        return params;
    }

    editHeadlineCommunicationPic = async () => {
        const params = this.getParamEdit();
        Site.blockUI();
        const url = Site.resolveClientUrl('AccountDetail/EditPic');
        await DataService.postDataAsync(url, params).then(async response => {
            if (response.data.findIndex(x => !x.isSuccessful) !== -1) {
                toast.error(response.data.find(x => !x.isSuccessful).message);
            } 
        }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);
    }

    getPicCommunicationTools() {
        let { otherAccountCommunicationInfos } = this.state.customerInfo;
        let picCommunicationTools = [];
        otherAccountCommunicationInfos.map((picCom, indexCom) => {
            const index = picCommunicationTools.findIndex(item => item.communicationID === picCom.communicationID);
            if (index >= 0 && index !== indexCom) {
                const newValue = picCommunicationTools[index].communicationValue.concat(', ', picCom.communicationValue);
                picCommunicationTools[index].communicationValue = newValue;
            }
            else {
                const newPicCom = {
                    communicationID: picCom.communicationID,
                    communicationValue: picCom.communicationValue
                };
                picCommunicationTools.push({ ...newPicCom });
            }
        });
        return picCommunicationTools;
    }

    editOtherAccountCommunicationInfo = async () => {
        const params = {
            custID: this.props.customerDetail.custId,
            otherCommunicationTools: this.getPicCommunicationTools()
        };

        Site.blockUI();
        const url = Site.resolveClientUrl('AccountDetail/EditOtherAccCommunicationInfo');
        await DataService.postDataAsync(url, params).then(async response => {
            if (!response.data.isSuccessful) {
                toast.error(response.data.message);
            }
        }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);
    }

    checkChattypeMapping = async () => {
        let validResult = await this.validateChattypeMappingPic();
        if (!validResult || validResult.length === 0) {            
            this.createFeedback();
        }
        else {
            const { params } = this.props.confirmCreateGuestDialog;
            this.setState({
                checkChattypeMappingDialog: {
                    show: true,
                    data: validResult
                }
            });
            this.props.setConfirmCreateGuestDialog({ show: false, params: params });
        }
    }

    checkCustomerExistsOnCRM = async () => {
        Site.blockUI();
        const url = Site.resolveClientUrl('AccountDetail/CheckCustomerExistsOnCRM');
        await DataService.postDataAsync(url, { customerId: this.props.customerDetail?.custId }).then(async response => {
            if (response.data === 1) {
                this.checkChattypeMapping();
            } else {
                await this.updateNewCrmCustomer();
            }
        }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);
    }

    updateNewCrmCustomer = async () => {
        const { customerDetail } = this.props;
        const params = GetParamsNewUser(customerDetail.custId, customerDetail);
        Site.blockUI();
        const url = Site.resolveClientUrl('AccountDetail/EditCustomerInfoDetail');
        await DataService.postDataAsync(url, params).then(async response => {
            if (response.data.isSuccessful) {
                this.checkChattypeMapping();
            }
        }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);
    }

    createFeedback = async () => {
        this.setState({ checkChattypeMappingDialog: { show: false, data: [] } });
        if (this.state.customerInfo.isOverwriteInfo && !this.props.customerDetail?.isGroupHeadLine) {
            await this.editOtherAccountCommunicationInfo();
        }
        const { params } = this.props.confirmCreateGuestDialog;
        this.formik.setSubmitting(true);

        this.props.addFeedback(params).then(() => {
            this.setState({ checkDuplicateDialog: { show: false } });
            this.props.setConfirmCreateGuestDialog({ show: false });
            if (this.props.addFeedbackResult?.isSuccessful) {
                const paramsCustomer = {
                    searchInfo: params.UserName,
                    isGuest: !this.props.currentCustomer ? true : this.props.currentCustomer.isGuest
                };
                const url = Site.resolveClientUrl('CustomerInfo/GetCustomerInfo');
                DataService.postDataAsync(url, paramsCustomer).then(response => {
                    if (!response?.data) {
                        return;
                    }
                    if (this.props.addFeedbackResult.isSuccessful) {
                        window.dispatchEvent(new Event('getCurrentCustomer'));
                        const data = response.data;
                        const currentCustomer = {
                            custId: data.custId,
                            isGuest: data.isGuest,
                            username: data.username,
                            isCreditSite: data.customerType === 1
                        };
                        const state = this.props.currentCustomer || currentCustomer;
                        setTimeout(() => {
                            if((this.props.currentCustomer && params.IsOverWrite) || !this.props.currentCustomer){
                                window.dispatchEvent(new Event('getCurrentCustomer'));
                                window.localStorage.setItem('updateLeftPanel', data.custId);
                            }
                            this.props.navigate(Site.resolveClientUrl('Dashboard'), {state: state});
                        }, 3000);
                    }
                }).catch(Site.handleAxiosError);
            }else{
                this.formik.setSubmitting(false);
            }
        }).catch(Site.handleAxiosError);
    };

    render() {
        const { settings, customerDetail } = this.props;
        if (this.state.content.autoGenerated === '') {
            return null;
        }

        const initialValues = customerDetail !== null ?
            initValuesAddCustomerFb(settings, customerDetail, this.state.customerInfo) :
            initValues(settings, this.state.customerInfo);
        return (
            <Formik
                innerRef={el => this.formik = el}
                initialValues={initialValues}
                validate={values => validateFormik(values, customerDetail, settings, this.state)}
                onSubmit={this.handleSubmit}
            >
                {this.renderForm}
            </Formik>
        );
    }
}

const FunctionBarWithNavigation = WithNavigation(CreateForm);
export default FunctionBarWithNavigation;
