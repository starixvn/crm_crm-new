import React, { Component, lazy, Suspense } from 'react';
import moment from 'moment';
import { Button, Col, Form, Row, OverlayTrigger, Tooltip, Collapse } from 'react-bootstrap';
import { Formik } from 'formik';
import FormikErrorMessage from '@jsroot/components/FormikErrorMessage';
import ResponseMessage from '@jsroot/components/ResponseMessage';
import LangHelper from '@jsroot/common/langHelper';
import { validateFormik, initValues, initCustomerInfo, initValuesAddCustomerFb, getParams } from './common.functions';
import DateTimeService from '@jsroot/common/dateTimeService';
import {
    getSubCategories, getSubProducts, getBetTypes, generateTimeAndToolPrefix,
    getSubjectOnChangeCategories
}
    from '@jsroot/common/shareScripts';
import Site from '@jsroot/common/site';
import Detail from './Detail';
import SweetModalDialog from '@jsroot/components/SweetModalDialog';
import AutoComplete from '@jsroot/components/AutoComplete';
import VerifyCustomer from '@jsroot/components/verifyCustomer';
import { BorderStyle  } from '@jsroot/common/constants';
import DataService from '@jsroot/common/dataService';
const CustomerInfo = lazy(() => import('./CustomerInfo'));
const Content = lazy(() => import('./Content'));

export default class CreateForm extends Component {
    constructor(props) {
        super(props);
        const currentClientTime = window.currentClientTime;
        this.state = {
            feedbackDate: new Date(DateTimeService.toShortDateTimeFormat(new Date(currentClientTime))),
            autoGeneratedInit: '',
            collapse: {
                isShowCustomerDetailOption: false,
                isShowDetailsOption: false,
                isVerifyCustomer: false,
                description: false,
                solution: false
            },
            editBlock: {
                isEditDescription: true,
                isEditSolution: true
            },
            communicationToolVal: '',
            subCategoriesOptions: [],
            subProductOptions: [],
            betTypeOptions: [],
            listOfCustomerValid: [],
            listOfCustomer: [],
            countClickRefTicket: 0,
            checkDuplicateDialog: { show: false },
            duplicateFeedbackId: 0,
            customerInfo: {
                title: props.settings.titles[0].id,
                firstName: '',
                lastName: '',
                birthday: '',
                passportNo: '',
                licenseeType: props.settings.licenseeTypes[0].id,
                countryCode: '',
                phoneNumber: '',
                areaCode: '',
                countryCode2: '',
                phoneNumber2: '',
                areaCode2: '',
                countryCode3: '',
                phoneNumber3: '',
                areaCode3: '',
                mobileCountryCode: '',
                mobileAreaCode: '',
                mobilePhoneNumber: '',
                faxCountryCode: '',
                faxAreaCode: '',
                faxNumber: '',
                pic1Name: '',
                pic1PhoneNumber: '',
                pic2Name: '',
                pic2PhoneNumber: '',
                pic3Name: '',
                pic3PhoneNumber: '',
                pic4Name: '',
                pic4PhoneNumber: '',
                skype: '',
                email: '',
                telegram: '',
                weChat: '',
                whatApp: '',
                line: '',
                letstalk: '',
                qq: '',
                zalo: '',
                isOverwriteInfo: false
            },
            content: {
                autoGenerated: '',
                description: '',
                solution: ''
            }
        };
    }
    componentDidMount() {
        const autoGenerated = this.renderAutoGeneratedText();
        this.setState({ content: {...this.state.content, autoGenerated }});
        if(this.props.customerDetail !== undefined && this.props.customerDetail !== null){
            const customerInfo = initCustomerInfo(this.props.customerDetail);
            this.setState({customerInfo});
        }
    }

    renderOptions = (name, item) => <option key={item} value={item}>{name}</option>;

    handleChangeFeedbackTime = (setFieldValue, feedbackDate, resolutionTime) => {
        setFieldValue('feedbackDate', feedbackDate);

        if (moment(feedbackDate).isAfter(moment(resolutionTime))) {
            resolutionTime = new Date(DateTimeService.toShortDateTimeFormat(new Date(feedbackDate)));
            resolutionTime.setMinutes(resolutionTime.getMinutes() + 1);

            setFieldValue('resolutionTime', resolutionTime);
        }

        this.setState({ feedbackDate }, () => {
            const autoGenerated = this.renderAutoGeneratedText();
            this.handleChangeContent('autoGenerated', autoGenerated);
        });
    };

    handleChangeResolutionTime = (setFieldValue, feedbackDate, resolutionTime) => {
        setFieldValue('resolutionTime', resolutionTime);

        if (moment(feedbackDate).isAfter(moment(resolutionTime))) {
            feedbackDate = new Date(DateTimeService.toShortDateTimeFormat(new Date(resolutionTime)));
            feedbackDate.setMinutes(feedbackDate.getMinutes() - 1);

            setFieldValue('feedbackDate', feedbackDate);
        }
    };

    handleCommunicationChange = (currentItem, selectedItemsKey, setFieldValue) => {
        setFieldValue('communication', selectedItemsKey);
        const { communicationTools } = this.props.settings;
        let communicationToolVal = '';
        if (selectedItemsKey.split(',').length === communicationTools.length) {
            communicationToolVal = communicationTools[0].name;
        } else if (currentItem !== '' && selectedItemsKey !== '' && currentItem.checked) {
            communicationToolVal = currentItem.name;
        } else if (selectedItemsKey !== '') {
            const firstCommIns = selectedItemsKey.split(',')[0];
            communicationToolVal = communicationTools.filter(x => x.id.toString() === firstCommIns)[0].name;
        }
        this.setState({ communicationToolVal }, () => {
            const autoGenerated = this.renderAutoGeneratedText();
            this.handleChangeContent('autoGenerated', autoGenerated);
        });
    };

    handleCollapseExpend = section => {
        this.setState(prevState => ({
            collapse: { ...prevState.collapse, [section]: !prevState.collapse[section] }
        }));
    };

    handleEditBlock = (event, section) => {
        event.stopPropagation();
        this.setState(prevState => ({
            editBlock: { ...prevState.editBlock, [section]: !prevState.editBlock[section] }
        }));
    };

    mainCategoriesHandleChange = (currentItem, selectedItemsKey, setFieldValue, values) => {
        if (selectedItemsKey) {
            const tempSubject = getSubjectOnChangeCategories(selectedItemsKey ? selectedItemsKey.split(',') : [],
                values.subject,
                this.props.settings.mainCategories);
            setFieldValue('subject', tempSubject);
            setFieldValue('category', selectedItemsKey);
            const subCategories = this.props.settings.subCategories;
            const selectedMainCategories = selectedItemsKey.split(',');
            const subCategoriesSelectedArr = values.subCategory.length > 0 ? values.subCategory.split(',') : [];
            const findSubByMain = getSubCategories(selectedMainCategories, subCategories, subCategoriesSelectedArr, false);
            this.setState({ subCategoriesOptions: findSubByMain });
        } else {
            this.setState({
                subCategoriesOptions: []
            });
            setFieldValue('subCategory', '');
            setFieldValue('subject', '');
        }
    };

    productHandleChange = (currentItem, selectedItemsKey, setFieldValue, subProductSelected) => {
        if (selectedItemsKey) {
            setFieldValue('product', selectedItemsKey);
            const subProducts = this.props.settings.subProducts;
            const selectedProduct = selectedItemsKey.split(',');
            const subProductSelectedArr = subProductSelected.length > 0 ? subProductSelected.split(',') : [];
            const findSubProductByProduct = getSubProducts(selectedProduct, subProducts, subProductSelectedArr, false);
            this.setState({ subProductOptions: findSubProductByProduct });
        } else {
            this.setState({
                subProductOptions: [],
                betTypeOptions: []
            });
            setFieldValue('subProduct', '');
            setFieldValue('betType', '');
        }
    };

    subProductHandleChange = (currentItem, selectedItemsKey, setFieldValue, betTypesSelected) => {
        setFieldValue('subProduct', selectedItemsKey);
        if (selectedItemsKey) {
            const betTypes = this.props.settings.bettypes;
            const selectedSubProducts = selectedItemsKey.split(',');
            const betTypeSelectedArr = betTypesSelected.length > 0 ? betTypesSelected.split(',') : [];
            const findBetTypeBySubProduct = getBetTypes(selectedSubProducts, betTypes, betTypeSelectedArr, false);
            this.setState({ betTypeOptions: findBetTypeBySubProduct });
        } else {
            this.setState({
                betTypeOptions: []
            });
            setFieldValue('betType', '');
        }
    };

    handleVerify = (event, setFieldValue, value) => {
        event.preventDefault();
        const regex1 = new RegExp(/,\s+/g);
        const regex2 = new RegExp(/^,+|,+$/g);
        const regex3 = new RegExp(/,{2,}/g);
        const customersInput = value.trim().replace(regex1, ',') // NOSONAR
            .replace(regex2, '') // NOSONAR
            .replace(regex3, ','); // NOSONAR
        const isValid = customersInput.split(',').filter(value => value.length > 50).length === 0;

        if (isValid) {
            this.props.setAddFeedback(null);
            this.props.verifyUserName({ Username: customersInput }).then(data => {
                let customers = [...this.state.listOfCustomer, ...data];
                customers = customers.filter((v, i, a) => a.findIndex(t => t.custId === v.custId && t.val === v.val) === i);
                this.setState({
                    listOfCustomer: customers,
                    listOfCustomerValid: customers.filter(item => item.custId !== 0)
                }, () => {
                    const autoGenerated = this.renderAutoGeneratedText();
                    this.handleChangeContent('autoGenerated', autoGenerated);
                });
            });
            setFieldValue('isVerifiedCustomers', true);
        }
        setFieldValue('customerNameInput', '');
    };

    handleReVerifyInactiveAndConfirm = (values, userNames) => {
        this.props.verifyUserName({ Username: userNames }).then(data => {
            const inactiveCustomers = data.filter(customer=> !customer.isSiteActive && customer.custId !== 0 && customer.isLicensee);
            this.setState({listOfCustomer: data});
            if(inactiveCustomers.length > 0){
                const inactiveUserName = inactiveCustomers.map(x=>x.val).join(',');
                const message = LangHelper.getResource('ErrorMessageInactiveSiteRelate') + inactiveUserName;
                this.props.setAddFeedback({isSuccessful: false, message});
            } else{
                this.props.setAddFeedback(null);
                this.handleConfirm(values);
            }
        });
    };

    onPasteCustomerHandler = (event, customers, setFieldValue) => {
        const customer = customers.trim();
        const items = (event.clipboardData || window.clipboardData).getData('text').replace(/ /g, ',')
            .replace(/\r\n/g, ',').replace(/\n/g, ',').replace(/\t/g, ',').split(',').filter(item => item !== '');
        setTimeout(() => {
            const customersInput = (customer.length > 0 ? customer + ',' : '').concat(items.join(','));
            setFieldValue('customerNameInput', customersInput);
        }, 100);
    };

    deleteCustomerVerify = id => {
        const listOfCustomer = this.state.listOfCustomer.filter(item => item.custId !== id);
        const listOfCustomerValid = this.state.listOfCustomerValid.filter(item => item.custId !== id);
        this.setState({
            listOfCustomer,
            listOfCustomerValid
        });
    };

    handleGetFeedbackSubjectTemplates = Site.debounce(searchText => {
        if (searchText.length >= 2) {
            this.props.getFeedbackSubjectTemplates(searchText);
        } else {
            this.props.setFeedbackSubjectTemplates([]);
        }
    });

    handleCloseConfirmCreateGuestDialog = () => {
        this.props.setConfirmCreateGuestDialog({ show: false });
    };

    handleChangeRefTicket = (e, setFieldValue) => {
        const value = e.target.value > 19 ? e.target.value.slice(0, 19) : e.target.value;
        setFieldValue('ticketRefInput', value);
    };

    onPasteRefTicketHandler = event =>{
        if (event.clipboardData.getData('Text').match(/[^\d]/)) {
            event.preventDefault();
        }
    };

    handleClickFillEvent = (values, setFieldValue) =>{
        Site.blockUI();
        const description = this.state.content.description;
        const autoGenerated = '<span style=\"color: rgb(255, 0, 0);\">This is an auto-generated entry.</span>';
        const colorGenerated = 'color: rgb(255, 0, 0)';
        this.props.getTicketInfoByRef({ refno: parseInt(values.ticketRefInput, 10) }).then(data => {
            Site.unblockUI();
            setFieldValue('ticketRefInput', '');
            if(!data){
                return;
            }else if(data.errorCode !== '0') {
                this.props.setAddFeedback({isSuccessful: false, message: data.description});
            } else {
                let descriptionText = '';
                this.props.setAddFeedback(null);
                const isFirstInputAndHasData = description.length > 0 && this.state.countClickRefTicket === 0;
                const isNotFirstInputAndRemoveData = this.state.countClickRefTicket !== 0 && !description.includes(colorGenerated);
                if (isFirstInputAndHasData || isNotFirstInputAndRemoveData) {
                    descriptionText = `${data.description} <br> ${description}`;
                } else if (this.state.countClickRefTicket === 0) {
                    descriptionText = data.description;
                } else {
                    const removeAutoGenerate = data.description.replace(autoGenerated, '');
                    descriptionText = values.description + removeAutoGenerate;
                }
                this.handleChangeContent('description', descriptionText);
            }

            this.setState(prevState =>({
                countClickRefTicket: prevState.countClickRefTicket + 1
            }));
        });
    };

    generateCustomerPrefix = () => {
        const relatedCustomers = this.state.listOfCustomerValid;
        let customerJoin = '';
        if (relatedCustomers.length > 0) {
            customerJoin = relatedCustomers.map(cust => cust.val).join(', ');
        }
        return 'System ID: ' + customerJoin;
    };

    renderAutoGeneratedText = () => {
        const lastedCommunicationVal = this.state.communicationToolVal !== '' ? this.state.communicationToolVal : 'N/A';
        const generateTime = generateTimeAndToolPrefix(this.state.feedbackDate, lastedCommunicationVal);
        const generateCustomer = this.generateCustomerPrefix();
        return `${generateTime}\n${generateCustomer}`;
    };

    handleChangeContent = (name, value) => {
        this.setState({ content: {...this.state.content, [name]: value }});
    };

    handleChangeCustomerInfo = event => {
        this.setState({ customerInfo: {...this.state.customerInfo, [event.target.name]: event.target.value }});
    };

    handleChangeValueInfo = (name, value) => {
        this.setState({ customerInfo: {...this.state.customerInfo, [name]: value }});
    };

    renderIdentityInformation = (values, errors, touched, handleChange) => {
        const {customerDetail} = this.props;
        const {isShowCustomerDetailOption} = this.state.collapse;
        const isCollapse = customerDetail === null ? !isShowCustomerDetailOption : isShowCustomerDetailOption;
        const borderStyle = !isCollapse ? BorderStyle.bottom : '';
        return (
            <div className={`panel-group ${BorderStyle.bottom}`}>
                {
                    customerDetail === null ?
                    <Form.Group as={Row} className={`title ${borderStyle}`}
                        aria-controls="collapse-expand-identity"
                        aria-expanded={isCollapse}
                    >
                        <Form.Label column sm="2" md="2" className='required'
                            onClick={() => this.handleCollapseExpend('isShowCustomerDetailOption')}
                        >
                            {LangHelper.getResource('IdentityInformation')}
                        </Form.Label>
                        {
                                <Col sm="2" md="2">
                                    <Form.Control type="text" size="sm" value={values.identityInformation}
                                        name="identityInformation" id="identityInformation"
                                        className="shadow-none" autoComplete="off"
                                        isInvalid={touched.identityInformation && errors.identityInformation}
                                        onChange={handleChange}
                                    />
                                </Col>
                        }
                    </Form.Group> :
                    <Form.Group as={Row} className={`title ${borderStyle}`}
                        aria-controls="collapse-expand-identity"
                        aria-expanded={isCollapse}
                        onClick={() => this.handleCollapseExpend('isShowCustomerDetailOption')}
                    >
                        <Form.Label column sm="2" md="2" className='username'>{customerDetail.username}</Form.Label>
                    </Form.Group>
                }
                <Collapse in={isCollapse}>
                    <div id="collapse-expand-show-identity">
                        {
                             <Suspense fallback={<div>Loading...</div>}>
                                <CustomerInfo
                                    customerDetail={customerDetail}
                                    customerInfo={this.state.customerInfo}
                                    handleChange={this.handleChangeCustomerInfo}
                                    handleChangeValueInfo={this.handleChangeValueInfo}
                                    settings={this.props.settings}
                                    renderOptions={this.renderOptions}
                                />
                             </Suspense>
                        }
                    </div>
                </Collapse>
            </div>
        );
    };

    renderDetails = (values, errors, touched, handleChange, setFieldValue) => {
        const collapse = this.state.collapse;
        const customerDetail = this.props.customerDetail;
        return (
            <div>
                <div className={`panel-group ${!collapse.isShowDetailsOption ? BorderStyle.bottom : ''}`}>
                    <Form.Group as={Row} className={`title ${BorderStyle.bottom}`}
                        onClick={() => this.handleCollapseExpend('isShowDetailsOption')}
                        aria-controls="collapse-expand-detail"
                        aria-expanded={!collapse.isShowDetailsOption}
                    >
                        <Form.Label column sm="2" md="2" className="required">
                            {LangHelper.getResource('Details')}
                        </Form.Label>
                    </Form.Group>
                </div>
                <Collapse in={!collapse.isShowDetailsOption}>
                    <div className={`panel-group ${BorderStyle.bottom}`} id="collapse-expand-show-detail">
                        <Detail
                            settings={this.props.settings} customerDetail={customerDetail} handleChange={handleChange}
                            values={values} errors={errors} touched={touched} setFieldValue ={setFieldValue} handleChangeFeedbackTime={this.handleChangeFeedbackTime}
                            handleChangeResolutionTime={this.handleChangeResolutionTime} handleCommunicationChange={this.handleCommunicationChange}
                            subCategoriesOptions={this.state.subCategoriesOptions} subProductOptions={this.state.subProductOptions}
                            betTypeOptions={this.state.betTypeOptions} renderOptions={this.renderOptions} mainCategoriesHandleChange={this.mainCategoriesHandleChange}
                            productHandleChange={this.productHandleChange} subProductHandleChange={this.subProductHandleChange}
                        />
                        {this.renderVerifyCustomer(values, handleChange, setFieldValue)}
                        <VerifyCustomer listOfCustomers={this.state.listOfCustomer} onClick={this.deleteCustomerVerify} />
                        {this.renderRefTicket(values, setFieldValue)}
                        <Form.Group as={Row} className="pt-1 pb-2">
                            <Form.Label className="required col-subject-width form-label col-form-label">
                                {LangHelper.getResource('Subject')}
                            </Form.Label>
                            <Col className="subject-auto-complete-container">
                                <AutoComplete
                                    options={this.props.feedbackSubjectTemplates} displayField="subject" value={values.subject}
                                    onChange={value => setFieldValue('subject', value.subject)} isInvalid={touched.subject && errors.subject}
                                    onInputChange={searchText => this.handleGetFeedbackSubjectTemplates(searchText)}
                                />
                            </Col>
                        </Form.Group>
                        {
                            customerDetail === null &&
                            <Suspense fallback={<div>Loading...</div>}>
                                <Content
                                    editBlock={this.state.editBlock} collapse={this.state.collapse} isInValidSolution={touched.solution && errors.solution}
                                    content={this.state.content} handleEditBlock={this.handleEditBlock} isValidDescription={touched.description && errors.description}
                                    handleCollapseExpend={this.handleCollapseExpend} handleChangeContent ={this.handleChangeContent}
                                />
                             </Suspense>
                        }
                    </div>
                </Collapse >
                {
                    customerDetail !== null &&
                    <Suspense fallback={<div>Loading...</div>}>
                        <Content
                            editBlock={this.state.editBlock} collapse={this.state.collapse} isInValidSolution={touched.solution && errors.solution}
                            content={this.state.content} handleEditBlock={this.handleEditBlock} isValidDescription={touched.description && errors.description}
                            handleCollapseExpend={this.handleCollapseExpend} handleChangeContent ={this.handleChangeContent}
                        />
                    </Suspense>
                }
            </div>
        );
    };

    renderVerifyCustomer = (values, handleChange, setFieldValue) =>{
        return (
            <Form.Group as={Row} className="pt-1 pb-2">
                <Col sm="2" md="2">
                    <Form.Check type="checkbox" id="check-box-verify" label={LangHelper.getResource('IsRelatedToCustomer')}
                        htmlFor="check-box-verify" checked={this.state.collapse.isVerifyCustomer}
                        onChange={() => this.handleCollapseExpend('isVerifyCustomer')}
                    />
                </Col>
                <Col sm="1" md="1">
                    <Form.Label>
                        <OverlayTrigger placement="bottom-start" overlay={
                            <Tooltip id={'add-feedback-tooltip-customers'}>
                                {LangHelper.getResource('MultipleCustomersTooltip')}
                            </Tooltip>}
                        >
                            <span className="fa fa-question-circle-o" />
                        </OverlayTrigger>
                    </Form.Label>
                </Col>
                <Col sm="9" md="9">
                    <Row>
                        <Col sm="10" md="10">
                            <Form.Control type="text" size="sm" value={values.customerNameInput} disabled={!this.state.collapse.isVerifyCustomer}
                                name="customerNameInput" className="shadow-none" autoComplete="off" onChange={handleChange}
                                onPaste={event => this.onPasteCustomerHandler(event, values.customerNameInput, setFieldValue)}/>
                        </Col>
                        <Col sm="2" md="2">
                            <Button name="isVerifiedCustomers" id="isVerifiedCustomers" type="submit" variant="primary"
                                disabled={!this.state.collapse.isVerifyCustomer}
                                size="sm" onClick={event => this.handleVerify(event, setFieldValue, values.customerNameInput)}>
                                {LangHelper.getResource('Verify')}
                            </Button>
                        </Col>
                    </Row>
                </Col>
            </Form.Group>
        );
    };

    renderRefTicket = (values, setFieldValue) => {
        return (
            <Form.Group as={Row}>
                <Col sm="4" md="4">
                    <Form.Group as={Row}>
                        <Form.Label column md="3" sm="3" htmlFor="ticketRefNo">{LangHelper.getResource('TicketRefNo')}</Form.Label>
                        <Col sm="1" md="1">
                        <Form.Label>
                            <OverlayTrigger placement="auto" overlay={
                                <Tooltip id='add-feedback-tooltip-ref-ticket'>
                                    {LangHelper.getResource('TooltipRefTicket') + this.props.balanceUpday}
                                </Tooltip>}
                            >
                                <span className="fa fa-question-circle-o" />
                            </OverlayTrigger>
                        </Form.Label>
                        </Col>
                        <Col sm="8" md="8" className="ref-ticket-input">
                            <Form.Control type="number" size="sm"
                                value={values.ticketRefInput}
                                onPaste={event => this.onPasteRefTicketHandler(event)}
                                id="refNo" name="refNo" className="shadow-none" autoComplete="off"
                                onChange={e =>this.handleChangeRefTicket(e, setFieldValue)}
                            />
                        </Col>
                    </Form.Group>
                </Col>
                <Col sm="4" md="4">
                    <Form.Group as={Row}>
                        <Col>
                            <Button disabled={values.ticketRefInput === ''} onClick={() =>this.handleClickFillEvent(values, setFieldValue)}>
                                {LangHelper.getResource('FillEventDetails')}
                            </Button>
                        </Col>
                    </Form.Group>
                </Col>
            </Form.Group>
        );
    };

    renderForm = ({
        values,
        errors,
        touched,
        handleChange,
        handleSubmit,
        setFieldValue
    }) => {
        return (
            <Form noValidate onSubmit={handleSubmit}>
                <FormikErrorMessage touched={touched} errors={errors} fieldNames={Object.keys(values)} />
                {
                    this.props.addFeedbackResult &&
                    <ResponseMessage isSuccessful={this.props.addFeedbackResult.isSuccessful}
                        message={this.props.addFeedbackResult.message || LangHelper.getResource('AddFeedbackSuccessfully')}/>
                }
                {
                    this.renderIdentityInformation(values, errors, touched, handleChange)
                }
                {
                    this.renderDetails(values, errors, touched, handleChange, setFieldValue)
                }
                {
                    this.props.confirmCreateGuestDialog.show &&
                    <SweetModalDialog size="lg"
                        title={LangHelper.getResource('Confirmation')}
                        contents={<div dangerouslySetInnerHTML={{ __html: this.props.confirmCreateGuestDialog.confirmMessage }} />}
                        buttons={[
                            <Button variant="primary" size="sm" onClick={this.handleCreateFeedback}>
                                {LangHelper.getResource('OK')}
                            </Button>,
                            <Button variant="primary" size="sm" onClick={this.handleCloseConfirmCreateGuestDialog}>
                                {LangHelper.getResource('Cancel')}
                            </Button>]}
                        onClose={this.handleCloseConfirmCreateGuestDialog}
                    />
                }
                {
                    this.state.checkDuplicateDialog.show &&
                    <SweetModalDialog size="lg"
                        title={LangHelper.getResource('Warning')}
                        contents={<div>{`This customer has a similar log with running number ${this.state.duplicateFeedbackId}. Do you want to create this log?`}</div>}
                        buttons={[
                            <Button variant="primary" size="sm" onClick={this.createFeedback}>
                                {LangHelper.getResource('OK')}
                            </Button>,
                            <Button variant="primary" size="sm" onClick={this.handleCloseCheckDuplicateDialog}>
                                {LangHelper.getResource('Cancel')}
                            </Button>
                        ]}
                        onClose={this.handleCloseCheckDuplicateDialog}/>
                }
                <Form.Group as={Row} className="mt-3">
                    <Col>
                        <Button type="submit" variant="primary" size="sm">
                            {LangHelper.getResource('Save')}
                        </Button>
                    </Col>
                </Form.Group>
            </Form>
        );
    };

    handleSubmit = values => {
        const userNameInput = this.state.listOfCustomerValid.map(x=> x.val).join(',');
        if(userNameInput.length > 0) {
            this.handleReVerifyInactiveAndConfirm(values, userNameInput);
        } else{
            this.handleConfirm(values);
        }
    };

    handleConfirm = values => {
        const params = getParams(values, this.props.customerDetail, this.props.settings, this.state);
        const specialChars = ['<', '>', '#', '&'];
        const inValidName = this.props.customerDetail === null && specialChars.filter(x => params.UserName.indexOf(x) >= 0).length > 0;
        if (inValidName) {
            params.UserName = params.UserName.replace(/<|>|#|&/g, '');
            this.confirmCreateAddGuestFeedback(params, LangHelper.getResource('ConfirmAddGuestFeedbackSpecialChar'));
        } else {
            this.confirmCreateAddGuestFeedback(params, LangHelper.getResource('ConfirmAddGuestFeedback'));
        }
    };

    confirmCreateAddGuestFeedback = (params, confirmMessage) => {
        this.props.setConfirmCreateGuestDialog({
            show: true,
            params,
            confirmMessage
        });
    };

    handleCheckDuplicateFeedback = async params => {
        const url = 'Feedback/CheckFeedbackDuplication';
        Site.blockUI();
        await DataService.postDataAsync(url, {
            customerId: params.CustId,
            categories: params.Categories,
            startTime: params.FeedbackDate
        }).then(response => {
            this.setState({ duplicateFeedbackId: response.data}, () =>{
                if (this.state.duplicateFeedbackId === 0) {
                    this.createFeedback();
                } else {
                    this.setState({ checkDuplicateDialog: {show: true} });
                }
            });
        }).then(() => Site.unblockUI());
    };

    handleCloseCheckDuplicateDialog = () => {
        this.setState({ checkDuplicateDialog: { show: false } });
        this.props.setConfirmCreateGuestDialog({ show: false });
    };

    handleCreateFeedback = () => {
        const { params } = this.props.confirmCreateGuestDialog;
        if(this.props.customerDetail !== null){
            this.handleCheckDuplicateFeedback(params);
        }else{
           this.createFeedback();
        }
    };

    createFeedback = async () => {
        const { params } = this.props.confirmCreateGuestDialog;
        await this.props.addFeedback(params).then(() => {
            this.handleCloseConfirmCreateGuestDialog();
            if (this.props.addFeedbackResult.isSuccessful) {
                const paramsCustomer = {
                    username: params.UserName,
                    isGuest: !this.props.currentCustomer ? true : this.props.currentCustomer.isGuest
                };
                const url = Site.resolveClientUrl('CustomerInfo/GetCustomerInfo');
                DataService.postDataAsync(url,paramsCustomer).then(response => {
                    if(!response || !response.data){
                        return;
                    }else{
                        setTimeout(() => {
                            window.location = Site.resolveClientUrl('');
                        }, 3000);
                    }
                });
            }
        });
    };

    render() {
        const {settings, customerDetail}= this.props;
        if (this.state.content.autoGenerated === '') {
            return null;
        }
        const initialValues = customerDetail !== null ? initValuesAddCustomerFb(settings, customerDetail) : initValues(settings);
        return (
            <Formik
                initialValues={initialValues}
                validate={values => validateFormik(values, customerDetail, settings, this.state.content)}
                onSubmit={this.handleSubmit}
            >
                {this.renderForm}
            </Formik>
        );
    }
}