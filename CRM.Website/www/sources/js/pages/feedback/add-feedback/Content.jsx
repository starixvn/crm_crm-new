import React, { PureComponent, lazy, Suspense } from 'react';
import { Form, Row, Collapse} from 'react-bootstrap';
import LangHelper from '@jsroot/common/langHelper';
import { BorderStyle  } from '@jsroot/common/constants';
const CkEditor = lazy(() => import('@jsroot/components/ckeditor/index'));

export default class Content extends PureComponent {
    renderEditBlockDescription = (content, handleEditBlock, collapse, handleChangeContent, handleCollapseExpend) => {
        return (
            <div>
                <div className={`panel-group ${BorderStyle.bottom}`}>
                    <Form.Group as={Row} className="title">
                        <Form.Label column sm="2" md="2">{LangHelper.getResource('AutoGenerated')}</Form.Label>
                    </Form.Group>
                    <Form.Group>
                        <div className="pt-1 pb-1">
                            <Form.Control as="textarea" rows={3} className="shadow-none" name="autoGenerated" id="autoGenerated"
                                value={content.autoGenerated} onChange={handleEditBlock}
                            />
                        </div>
                    </Form.Group>
                </div>
                <div className={`panel-group ${!collapse.description ? BorderStyle.bottom : ''}`}>
                    <div className="title edit_block border-bottom-0" onClick={() => handleCollapseExpend('description')}
                        aria-expanded={!collapse.description}
                        aria-controls="collapse-expand-remark"
                    >
                        <Form.Label className="required" column md="2" sm="2">{LangHelper.getResource('Description')}</Form.Label>
                        <div className="pr-3 float-right" onClick={e => handleEditBlock(e, 'isEditDescription')}>
                            <span>{LangHelper.getResource('Preview')}</span>
                        </div>
                    </div>
                    <Collapse in={!collapse.description}>
                        <div id="collapse-expand-remark" className="pt-1 pb-1">
                            {
                                 <Suspense fallback={<div>Loading...</div>}>
                                    <CkEditor
                                        name='description'
                                        isInvalid={this.props.isValidDescription}
                                        data={content.description}
                                        username={window.currentUsername}
                                        onChange={value => handleChangeContent('description', value)}
                                    />
                                 </Suspense>
                            }
                        </div>
                    </Collapse>
                </div>
            </div>
        );
    };

    renderPreviewDescription = (content, collapse, handleEditBlock, handleCollapseExpend) => {
        return (
            <div className={`panel-group ${collapse.description ? BorderStyle.bottom : ''}`}>
                <div className="title edit_block" onClick={() => handleCollapseExpend('description')}
                    aria-controls="collapse-expand-remark"
                    aria-expanded={!collapse.description}
                >
                    <Form.Label column sm="2" md="2" className="required">{LangHelper.getResource('Description')}</Form.Label>
                    <div className="float-right pr-3" onClick={e => handleEditBlock(e, 'isEditDescription')}>
                        <span>{LangHelper.getResource('Edit')}</span>
                    </div>
                </div>
                <Collapse in={!collapse.description}>
                    <div id="collapse-expand-remark" className="pt-1 pb-1">
                        <div style={{ whiteSpace: 'pre-line' }}>{content.autoGenerated}</div>
                        <div dangerouslySetInnerHTML={{ __html: content.description }} />
                    </div>
                </Collapse>
            </div>
        );
    };

    render() {
        const {editBlock, collapse, content, handleEditBlock, handleCollapseExpend, handleChangeContent, isValidSolution} = this.props;
        return (
            <div>
                {
                    editBlock.isEditDescription
                        ? this.renderEditBlockDescription(content, handleEditBlock, collapse, handleChangeContent, handleCollapseExpend)
                        : this.renderPreviewDescription(content, collapse, handleEditBlock, handleCollapseExpend)
                }
                <div className={`panel-group ${collapse.solution ? BorderStyle.bottom : ''}`}>
                    <div className="title edit_block" onClick={() => handleCollapseExpend('solution')}
                        aria-controls="collapse-expand-remark"
                        aria-expanded={!collapse.solution}
                    >
                        <Form.Label column sm="2" md="2" className="required">{LangHelper.getResource('Solution')}</Form.Label>
                        <div className="float-right pr-3" onClick={e => handleEditBlock(e, 'isEditSolution')}>
                            {
                                !editBlock.isEditSolution ?
                                    <span>{LangHelper.getResource('Edit')}</span>
                                    :
                                    <div>
                                        <span>{LangHelper.getResource('Preview')}</span>
                                    </div>
                            }

                        </div>
                    </div>
                    <Collapse in={!collapse.solution}>
                        {
                            !editBlock.isEditSolution ?
                                <div disabled className="shadow-none" name="previewDescription" id="previewSolution"
                                    dangerouslySetInnerHTML={{ __html: content.solution }}
                                />
                                :
                                <div id="collapse-expand-solution" className="pt-1 pb-1">
                                     <Suspense fallback={<div>Loading...</div>}>
                                        <CkEditor
                                            name='solution'
                                            isInvalid={isValidSolution}
                                            data={content.solution} username={window.currentUsername}
                                            onChange={value => handleChangeContent('solution', value)}
                                        />
                                     </Suspense>
                                </div>
                        }
                    </Collapse>
                </div>
            </div>
        );
    }
}