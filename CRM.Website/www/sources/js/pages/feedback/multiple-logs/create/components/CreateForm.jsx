import React, { Component } from 'react';
import { connect } from 'react-redux';
import { bindActionCreators } from 'redux';
import { Button, Col, Form, Row, OverlayTrigger, Tooltip, Collapse } from 'react-bootstrap';
import DatePicker from '@jsroot/components/date-picker/index';
import CkEditor from '@jsroot/components/CkEditor';
import { Formik } from 'formik';
import { ActionCreators } from '../actions';
import VerifyCustomerResult from './VerifyCustomerResult';
import FormikErrorMessage from '@jsroot/components/FormikErrorMessage';
import MultipleSelect from '@jsroot/components/multiple-select/index';
import Site from '@jsroot/common/site';
import DateTimeService from '@jsroot/common/dateTimeService';
import LangHelper from '@jsroot/common/langHelper';
import { getSubCategories, getSubProducts, getBetTypes } from '@jsroot/common/shareScripts';

export class CreateForm extends Component {
    constructor(props) {
        super(props);

        this.state = {
            collapse: {
                autoGenerated: false,
                remark: false,
                solution: false
            },
            subCategoryOptions: [],
            subProductOptions: [],
            betTypeOptions: []
        };
    }

    get initFormData() {
        const settings = this.props.settings;
        const startTime = new Date(DateTimeService.toShortDateTimeFormat(new Date(window.currentClientTime)));
        const endTime = new Date(DateTimeService.toShortDateTimeFormat(new Date(window.currentClientTime)));
        endTime.setMinutes(endTime.getMinutes() + 1);

        return {
            customerNameInput: '',
            startTime,
            endTime,
            extensionId: settings.extensions[0].id,
            languageId: settings.languages[0].settingId,
            countryId: settings.countries[0].id,
            communicationToolIds: '',
            mainCategoryIds: '',
            subCategoryIds: '',
            productIds: '',
            subProductIds: '',
            betTypeIds: '',
            statusId: settings.statuses[0].settingId,
            roleId: '',
            siteId: '',
            licenseeTypeId: '',
            responseId: settings.responses[0].id,
            noOfInquiries: '',
            subject: '',
            remark: "<div><font color=\"#ff0000\">" + 'This entry is created by Multiple Logs' + "</font></div><br/>",
            solution: '',
            isUseDefaultCommunicationTool: true,
            isUseDefaultLanguage: true,
            isUseDefaultCountry: true
        };
    }

    handleCollapseExpend = section => {
        this.setState(prevState => ({
            collapse: { ...prevState.collapse, [section]: !prevState.collapse[section] }
        }));
    };

    handlePasteCustomer = (event, customerNameInput, setFieldValue) => {
        const customer = customerNameInput.trim();
        const items = (event.clipboardData || window.clipboardData).getData('text')
            .replace(/ /g, ',')
            .replace(/\r\n/g, ',')
            .replace(/\n/g, ',')
            .replace(/\t/g, ',')
            .split(',').filter(item => item !== '');

        setTimeout(() => {
            const customerInput = (customer.length > 0 ? customer + ',' : '').concat(items.join(','));
            setFieldValue('customerNameInput', customerInput);
        }, 100);
    };

    verifyCustomers = (customerNameInput, setFieldValue) => {
        const username = customerNameInput.trim().replace(/,\s+/g, ',').replace(/^,+|,+$/g, '').replace(/,{2,}/g, ',');
        if (username === '') {
            return;
        }

        Site.blockUI();
        this.props.verifyCustomers({ username }).then(response => {
            this.props.setVerifyCustomerResults(response.data);
            setFieldValue('customerNameInput', '');

            Site.unblockUI();
        });
    };

    handleChangeMainCategory = (setFieldValue, selectedCategoryIds, selectedSubCategoryIds) => {
        setFieldValue('categoryIds', selectedCategoryIds);
        if (selectedCategoryIds) {
            const subCategoryIds = selectedSubCategoryIds.length > 0 ? selectedSubCategoryIds.split(',') : [];
            const subCategories = getSubCategories(selectedCategoryIds.split(','), this.props.settings.subCategories, subCategoryIds, false);
            this.setState({ subCategoryOptions: subCategories });
        } else {
            this.setState({ subCategoryOptions: [] });
        }
    };

    handleChangeProduct = (setFieldValue, selectedProductIds, selectedSubProductIds) => {
        setFieldValue('productIds', selectedProductIds);
        if (selectedProductIds) {
            const subProductIds = selectedSubProductIds.length > 0 ? selectedSubProductIds.split(',') : [];
            const subProducts = getSubProducts(selectedProductIds.split(','), this.props.settings.subProducts, subProductIds, false);
            this.setState({ subProductOptions: subProducts });
        } else {
            this.setState({ subProductOptions: [] });
        }
    };

    handleChangeSubProduct = (setFieldValue, selectedSubProductIds, selectedBetTypeIds) => {
        setFieldValue('subCategory', selectedSubProductIds);
        if (selectedSubProductIds) {
            const betTypeIds = selectedBetTypeIds.length > 0 ? selectedBetTypeIds.split(',') : [];
            const betTypes = getBetTypes(selectedSubProductIds.split(','), this.props.settings.bettypes, betTypeIds, false);
            this.setState({ betTypeOptions: betTypes });
        } else {
            this.setState({ betTypeOptions: [] });
        }
    };

    validateNoOfInquiries = event => {
        return event.target.validity.valid
            || event.target.value < 1 && (event.target.value = 1)
            || event.target.value > 32000 && (event.target.value = 32000);
    }

    validateFormik = values => {
        const errors = {};
        return errors;
    };

    handleSubmit = (values, { setSubmitting }) => {
    };

    renderForm = ({
        values,
        errors,
        touched,
        handleChange,
        handleSubmit,
        setFieldValue,
        isSubmitting
    }) => {
        const { collapse, subCategoryOptions, subProductOptions, betTypeOptions } = this.state;
        const { settings, verifyCustomerResults } = this.props;
        const { extensions, countries, communicationTools, languages, mainCategories, products, statuses, responses } = settings;

        return (
            <Form noValidate onSubmit={handleSubmit}>
                <FormikErrorMessage touched={touched} errors={errors} fieldNames={Object.keys(values)} />
                <div className="panel-group">
                    <div className="panel-content">
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2" htmlFor="customerNameInput" className="required">
                                {LangHelper.getResource('Listofcustomers')}
                            </Form.Label>
                            <Col sm="8" md="8">
                                <Form.Control type="text" size="sm" name="customerNameInput"
                                    className="shadow-none" autoComplete="off" value={values.customerNameInput}
                                    isInvalid={touched.customerNameInput && errors.customerNameInput}
                                    onPaste={event => this.handlePasteCustomer(event, values.customerNameInput, setFieldValue)}
                                    onChange={handleChange}
                                />
                            </Col>
                            <Col sm="1" md="1">
                                <Button type="button" variant="primary" size="sm" className="pull-right"
                                    disabled={values.customerNameInput.trim() === ''}
                                    onClick={() => this.verifyCustomers(values.customerNameInput, setFieldValue)}
                                >
                                    {LangHelper.getResource('Verify')}
                                </Button>
                            </Col>
                            <Col sm="1" md="1">
                                <OverlayTrigger
                                    placement="bottom-end"
                                    overlay={<Tooltip>Role, Site, Licensee Type shall be update automatically by system!</Tooltip>}
                                >
                                    <span className="fa fa-exclamation-circle" />
                                </OverlayTrigger>
                            </Col>
                        </Form.Group>
                        {
                            verifyCustomerResults.length > 0 &&
                            <Form.Group as={Row}>
                                <Form.Label column sm="2" md="2" />
                                <Col sm="9" md="9">
                                    <VerifyCustomerResult />
                                </Col>
                            </Form.Group>
                        }
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('StartTime')}</Form.Label>
                            <Col sm="3" md="3" className="react-datepicker-wrapper-container form-control-wrapper">
                                <DatePicker
                                    selected={values.startTime}
                                    timeInputLabel="Time:"
                                    dateFormat="MMM dd, yyyy hh:mm aa"
                                    showTimeInput
                                    onChange={value => setFieldValue('startTime', value)}
                                />
                            </Col>
                            <Col sm="1" md="1" />
                            <Form.Label column sm="2" md="2">Ext</Form.Label>
                            <Col sm="3" md="3">
                                <MultipleSelect
                                    dataSource={extensions}
                                    keyField='id'
                                    valueField='value'
                                    hasAllOption={extensions.length > 0}
                                    isAllTextShown={extensions.length > 0}
                                    hasSearchBox
                                    isNAOption
                                    onChange={(currentItem, selectedItemsKey) => {
                                        setFieldValue('extensionIds', selectedItemsKey);
                                    }}
                                />
                            </Col>
                        </Form.Group>
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('EndTime')}</Form.Label>
                            <Col sm="3" md="3" className="react-datepicker-wrapper-container form-control-wrapper">
                                <DatePicker
                                    selected={values.endTime}
                                    timeInputLabel="Time:"
                                    dateFormat="MMM dd, yyyy hh:mm aa"
                                    showTimeInput
                                    onChange={value => setFieldValue('endTime', value)}
                                />
                            </Col>
                            <Col sm="1" md="1" />
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('Country')}</Form.Label>
                            <Col sm="3" md="3">
                                <Form.Control as="select" size="sm" className="shadow-none"
                                    value={values.countryId} onChange={handleChange}
                                    disabled={values.isUseDefaultCountry}
                                >
                                    <option value="" hidden disabled />
                                    {
                                        countries.map(item =>
                                            <option key={item.id} value={item.id}>
                                                {item.name}
                                            </option>
                                        )
                                    }
                                </Form.Control>
                            </Col>
                            <Col sm="1" md="1">
                                <OverlayTrigger
                                    placement="left-start"
                                    overlay={<Tooltip>{LangHelper.getResource('ApplyDefaultCountry')}</Tooltip>}
                                >
                                    <Form.Check type="checkbox" checked={values.isUseDefaultCountry}
                                        onChange={event => setFieldValue('isUseDefaultCountry', event.target.checked)}
                                    />
                                </OverlayTrigger>
                            </Col>
                        </Form.Group>
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('CommunicationTool')}</Form.Label>
                            <Col sm="3" md="3">
                                <MultipleSelect
                                    dataSource={communicationTools}
                                    keyField='id'
                                    valueField='settingName'
                                    hasAllOption={communicationTools.length > 0}
                                    isAllTextShown={communicationTools.length > 0}
                                    hasSearchBox isDisable={values.isUseDefaultCommunicationTool}
                                    isNAOption
                                    onChange={(currentItem, selectedItemsKey) => {
                                        setFieldValue('communication', selectedItemsKey);
                                    }}
                                />
                            </Col>
                            <Col sm="1" md="1">
                                <OverlayTrigger
                                    placement="left-start"
                                    overlay={<Tooltip>{LangHelper.getResource('ApplyDefaultCommunicationTool')}</Tooltip>}
                                >
                                    <Form.Check type="checkbox" checked={values.isUseDefaultCommunicationTool}
                                        onChange={event => setFieldValue('isUseDefaultCommunicationTool', event.target.checked)}
                                    />
                                </OverlayTrigger>
                            </Col>
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('Language')}</Form.Label>
                            <Col sm="3" md="3">
                                <Form.Control as="select" size="sm" className="shadow-none"
                                    value={values.languageId} onChange={handleChange}
                                    disabled={values.isUseDefaultLanguage}
                                >
                                    <option value="" hidden disabled />
                                    {
                                        languages.map(item =>
                                            <option key={item.settingId} value={item.settingId}>
                                                {item.settingName}
                                            </option>
                                        )
                                    }
                                </Form.Control>
                            </Col>
                            <Col sm="1" md="1">
                                <OverlayTrigger
                                    placement="left-start"
                                    overlay={<Tooltip>{LangHelper.getResource('ApplyDefaultLanguage')}</Tooltip>}
                                >
                                    <Form.Check type="checkbox" checked={values.isUseDefaultLanguage}
                                        onChange={event => setFieldValue('isUseDefaultLanguage', event.target.checked)}
                                    />
                                </OverlayTrigger>
                            </Col>
                        </Form.Group>
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2" className="required">{LangHelper.getResource('Category')}</Form.Label>
                            <Col sm="3" md="3">
                                <MultipleSelect
                                    isInvalid={touched.categoryIds && errors.categoryIds}
                                    dataSource={mainCategories}
                                    keyField='mainCategoryID' valueField='settingName'
                                    hasAllOption={mainCategories.length > 0}
                                    isAllTextShown={mainCategories.length > 0}
                                    hasSearchBox isNAOption
                                    maxDisplayItemCount={1}
                                    onChange={(currentItem, selectedItemsKey) => {
                                        this.handleChangeMainCategory(setFieldValue, selectedItemsKey, values.subCategoryIds);
                                    }}
                                />
                            </Col>
                            <Col sm="1" md="1" />
                            <Form.Label column sm="2" md="2" className="required">{LangHelper.getResource('SubCategory')}</Form.Label>
                            <Col sm="3" md="3">
                                <MultipleSelect
                                    isInvalid={touched.subCategoryIds && errors.subCategoryIds}
                                    dataSource={subCategoryOptions}
                                    keyField='subCategoryId' valueField='settingName'
                                    hasAllOption={subCategoryOptions.length > 0}
                                    isAllTextShown={subCategoryOptions.length > 0}
                                    hasSearchBox isNAOption
                                    maxDisplayItemCount={1}
                                    onChange={(currentItem, selectedItemsKey) => {
                                        setFieldValue('subCategoryIds', selectedItemsKey);
                                    }}
                                />
                            </Col>
                        </Form.Group>
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('Product')}</Form.Label>
                            <Col sm="3" md="3">
                                <MultipleSelect
                                    dataSource={products}
                                    keyField='id' valueField='value'
                                    hasAllOption={products.length > 0}
                                    isAllTextShown={products.length > 0}
                                    hasSearchBox isNAOption
                                    maxDisplayItemCount={1}
                                    onChange={(currentItem, selectedItemsKey) => {
                                        this.handleChangeProduct(setFieldValue, selectedItemsKey, values.subCategoryIds);
                                    }}
                                />
                            </Col>
                            <Col sm="1" md="1" />
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('SubProduct')}</Form.Label>
                            <Col sm="3" md="3">
                                <MultipleSelect
                                    dataSource={subProductOptions}
                                    keyField='id' valueField='value'
                                    hasAllOption={subProductOptions.length > 0}
                                    isAllTextShown={subProductOptions.length > 0}
                                    hasSearchBox isNAOption
                                    maxDisplayItemCount={1}
                                    onChange={(currentItem, selectedItemsKey) => {
                                        this.handleChangeSubProduct(setFieldValue, selectedItemsKey, values.betTypeIds);
                                    }}
                                />
                            </Col>
                        </Form.Group>
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('Status')}</Form.Label>
                            <Col sm="3" md="3">
                                <Form.Control as="select" size="sm" className="shadow-none"
                                >
                                    <option value="" hidden disabled />
                                    {
                                        statuses.map(item =>
                                            <option key={item.settingId} value={item.settingId}>
                                                {item.settingName}
                                            </option>
                                        )
                                    }
                                </Form.Control>
                            </Col>
                            <Col sm="1" md="1" />
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('BetType')}</Form.Label>
                            <Col sm="3" md="3">
                                <MultipleSelect
                                    dataSource={betTypeOptions}
                                    keyField='id' valueField='value'
                                    hasAllOption={betTypeOptions.length > 0}
                                    isAllTextShown={betTypeOptions.length > 0}
                                    hasSearchBox isNAOption
                                    maxDisplayItemCount={1}
                                    onChange={(currentItem, selectedItemsKey) => {
                                        setFieldValue('betTypeIds', selectedItemsKey);
                                    }}
                                />
                            </Col>
                        </Form.Group>
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('Role')}</Form.Label>
                            <Col sm="3" md="3">
                                <Form.Control as="select" size="sm" className="shadow-none" disabled>
                                    <option value="">{LangHelper.getResource('NotApply')}</option>
                                </Form.Control>
                            </Col>
                            <Col sm="1" md="1" />
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('Site')}</Form.Label>
                            <Col sm="3" md="3">
                                <Form.Control as="select" size="sm" className="shadow-none" disabled>
                                    <option value="">{LangHelper.getResource('NotApply')}</option>
                                </Form.Control>
                            </Col>
                        </Form.Group>
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('Response')}</Form.Label>
                            <Col sm="3" md="3">
                                <Form.Control as="select" size="sm" className="shadow-none"
                                >
                                    <option value="" hidden disabled />
                                    {
                                        responses.map(item =>
                                            <option key={item.id} value={item.id}>
                                                {item.value}
                                            </option>
                                        )
                                    }
                                </Form.Control>
                            </Col>
                            <Col sm="1" md="1" />
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('LicenseeType')}</Form.Label>
                            <Col sm="3" md="3">
                                <Form.Control as="select" size="sm" className="shadow-none" disabled>
                                    <option value="">{LangHelper.getResource('NotApply')}</option>
                                </Form.Control>
                            </Col>
                        </Form.Group>
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2">{LangHelper.getResource('NoOfInquiries')}</Form.Label>
                            <Col sm="3" md="3">
                                <Form.Control type="number" size="sm" className="shadow-none" name="noOfInquiries"
                                    min={1} max={3200} value={values.noOfInquiries}
                                    onInput={this.validateNoOfInquiries} onChange={handleChange}
                                />
                            </Col>
                        </Form.Group>
                        <Form.Group as={Row}>
                            <Form.Label column sm="2" md="2" className="required">{LangHelper.getResource('Subject')}</Form.Label>
                            <Col sm="9" md="9">
                                <Form.Control type="text" size="sm"
                                    className="shadow-none" autoComplete="off"
                                />
                            </Col>
                        </Form.Group>
                    </div>
                </div>
                <div className="panel-group">
                    <Form.Group as={Row} className="panel-title" onClick={() => this.handleCollapseExpend('autoGenerated')}
                        aria-controls="collapse-expand-autoGenerated"
                        aria-expanded={!collapse.autoGenerated}
                    >
                        <Form.Label>{LangHelper.getResource('AutoGenerated')}</Form.Label>
                    </Form.Group>
                    <Collapse in={!collapse.autoGenerated}>
                        <div className="panel-content">
                            <Form.Control as="textarea" rows={3} className="shadow-none" name="autoGenerated"
                                value={values.autoGenerated} onChange={handleChange}
                            />
                        </div>
                    </Collapse>
                </div>
                <div className="panel-group">
                    <Form.Group as={Row} className="panel-title" onClick={() => this.handleCollapseExpend('remark')}
                        aria-controls="collapse-expand-remark"
                        aria-expanded={!collapse.remark}
                    >
                        <Form.Label className="required">{LangHelper.getResource('Remark')}</Form.Label>
                    </Form.Group>
                    <Collapse in={!collapse.remark}>
                        <div id="collapse-expand-remark" className="panel-content">
                            <CkEditor data={values.remark} onChange={value => setFieldValue('remark', value)} />
                        </div>
                    </Collapse>
                </div>
                <div className="panel-group">
                    <Form.Group as={Row} className="panel-title" onClick={() => this.handleCollapseExpend('solution')}
                        aria-controls="collapse-expand-solution"
                        aria-expanded={!collapse.solution}
                    >
                        <Form.Label className="required">{LangHelper.getResource('Solution')}</Form.Label>
                    </Form.Group>
                    <Collapse in={!collapse.solution}>
                        <div id="collapse-expand-solution" className="panel-content">
                            <CkEditor data={values.solution} onChange={value => setFieldValue('solution', value)} />
                        </div>
                    </Collapse>
                </div>
                <Form.Group as={Row} className="mt-3">
                    <Col>
                        <Button type="submit" variant="primary" size="sm" disabled={isSubmitting}>
                            {LangHelper.getResource('Save')}
                        </Button>
                    </Col>
                </Form.Group>
            </Form>
        );
    };

    render() {
        const initialValues = this.initFormData;
        return (
            <Formik
                initialValues={initialValues}
                validate={values => this.validateFormik(values)}
                onSubmit={this.handleSubmit}
            >
                {this.renderForm}
            </Formik>

        );
    }
}

const mapDispatchToProps = dispatch => bindActionCreators(ActionCreators, dispatch);

const mapStateToProps = state => {
    const {
        settings, verifyCustomerResults
    } = state;
    return {
        settings, verifyCustomerResults
    };
};

export default connect(mapStateToProps, mapDispatchToProps)(CreateForm);