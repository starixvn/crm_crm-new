import React from 'react';
import { shallow } from 'enzyme';
import { CreateForm } from '../CreateForm';
import Site from '@jsroot/common/site';
import DateTimeService from '@jsroot/common/dateTimeService';
import LangHelper from '@jsroot/common/langHelper';
import * as shareScripts from '@jsroot/common/shareScripts';

describe('CreateForm', () => {
    const defaultProps = {
        settings: {
            extensions: [{ id: 1 }],
            languages: [{ languageId: 1 }],
            countries: [{ id: 1 }],
            statuses: [{ statusId: 1 }],
            responses: [{ id: 1 }]
        }
    };

    beforeAll(() => {
        window.currentClientTime = '7/28/2021 2:26:28 PM';
        jest.useFakeTimers();
        Site.blockUI = jest.fn();
        Site.unblockUI = jest.fn();
        LangHelper.getResource = jest.fn(key => key);
    });

    afterAll(() => {
        jest.clearAllMocks();
    });

    describe('initFormData', () => {
        it('return as expected', () => {
            // Arrange
            shareScripts.generateTimeAndToolPrefix = jest.fn(() => 'time and tool');
            DateTimeService.toShortDateTimeFormat = jest.fn(() => '7/28/2021 2:26:28 PM');
            const startTime = new Date('7/28/2021 2:26:28 PM');
            const endTime = new Date('7/28/2021 2:26:28 PM');
            endTime.setMinutes(endTime.getMinutes() + 1);
            const expected = {
                customerNameInput: '',
                startTime,
                endTime,
                extensionIds: '1',
                languageId: 1,
                countryId: 1,
                communicationToolIds: '',
                categoryIds: '',
                subCategoryIds: '',
                productIds: '',
                subProductIds: '',
                betTypeIds: '',
                statusId: 1,
                roleId: '',
                siteId: '',
                licenseeTypeId: '',
                responseId: 1,
                noOfInquiries: '',
                subject: '',
                autoGenerated: 'time and tool \nSystem ID: ',
                remark: `<div><font color="#ff0000">This entry is created by Multiple Logs</font></div><br/>`,
                solution: '',
                isUseDefaultCommunicationTool: true,
                isUseDefaultLanguage: true,
                isUseDefaultCountry: true
            };
            const container = shallow(<CreateForm {...defaultProps} />).instance();

            // Act
            const actual = container.initFormData();

            // Assert
            expect(shareScripts.generateTimeAndToolPrefix).toHaveBeenCalledWith(startTime, '');
            expect(actual).toEqual(expected);
        });
    });

    describe('handleCollapseExpand', () => {
        it('should update state correct', () => {
            // Arrange
            const container = shallow(<CreateForm {...defaultProps} />).instance();

            // Act
            container.handleCollapseExpand('autoGenerated');

            // Assert
            expect(container.state.collapse).toEqual({
                autoGenerated: true,
                remark: false,
                solution: false
            });
        });
    });

    describe('handlePasteCustomer', () => {
        it('should do as expected', () => {
            // Arrange
            const customerNameInput = 'sa';
            const setFieldValue = jest.fn();
            const event = { clipboardData: { getData: jest.fn(() => 'test1, test2') } };
            const container = shallow(<CreateForm {...defaultProps} />).instance();

            // Act
            container.handlePasteCustomer(setFieldValue, event, customerNameInput);
            jest.runAllTimers();

            // Assert
            expect(setFieldValue).toHaveBeenCalledWith('customerNameInput', 'sa,test1,test2');
        });
    });

    describe('verifyCustomers', () => {
        it('should do nothing when customer input is empty', () => {
            // Arrange
            const setFieldValue = jest.fn();
            const props = {
                ...defaultProps,
                verifyCustomers: jest.fn()
            };
            const container = shallow(<CreateForm {...props} />).instance();

            // Act
            container.verifyCustomers(setFieldValue, '');

            // Assert
            expect(Site.blockUI).not.toHaveBeenCalled();
            expect(props.verifyCustomers).not.toHaveBeenCalled();
        });

        it('should do as expected when customer input has data', async () => {
            // Arrange
            const response = { data: [{ custId: 1, username: 'sa' }] };
            const promise = Promise.resolve(response);
            const setFieldValue = jest.fn();
            const props = {
                ...defaultProps,
                verifyCustomers: jest.fn(() => promise),
                setVerifyCustomerResults: jest.fn()
            };
            const container = shallow(<CreateForm {...props} />).instance();

            // Act
            container.verifyCustomers(setFieldValue, 'sa, test');
            await promise;

            // Assert
            expect(Site.blockUI).toHaveBeenCalled();
            expect(Site.unblockUI).toHaveBeenCalled();
            expect(setFieldValue).toHaveBeenCalledWith('customerNameInput', '');
            expect(props.verifyCustomers).toHaveBeenCalledWith({ username: 'sa,test' });
            expect(props.setVerifyCustomerResults).toHaveBeenCalledWith([{ custId: 1, username: 'sa' }]);
        });
    });

    describe('handleChangeStartTime', () => {
        it('should not update endTime when startTime is before endTime', () => {
            // Arrange
            const setFieldValue = jest.fn();
            const startTime = '7/28/2021 2:26:28 PM';
            const endTime = '7/28/2021 2:26:29 PM';
            const container = shallow(<CreateForm {...defaultProps} />).instance();
            container.updateTimeAndToolPrefix = jest.fn();

            // Act
            container.handleChangeStartTime(setFieldValue, startTime, endTime);
            jest.runAllTimers();

            // Assert
            expect(setFieldValue).toHaveBeenCalledWith('startTime', startTime);
            expect(container.updateTimeAndToolPrefix).toHaveBeenCalled();
        });

        it('should update endTime when startTime is before endTime', () => {
            // Arrange
            const setFieldValue = jest.fn();
            const startTime = '7/28/2021 2:26:28 PM';
            const endTime = '7/28/2021 2:26:27 PM';
            DateTimeService.toShortDateTimeFormat = jest.fn(() => '7/28/2021 2:26:28 PM');
            const container = shallow(<CreateForm {...defaultProps} />).instance();
            container.updateTimeAndToolPrefix = jest.fn();

            // Act
            container.handleChangeStartTime(setFieldValue, startTime, endTime);
            jest.runAllTimers();

            // Assert
            expect(setFieldValue.mock.calls[0]).toEqual(['startTime', startTime]);
            expect(setFieldValue).toHaveBeenLastCalledWith('endTime', new Date('7/28/2021 2:27:28 PM'));
            expect(container.updateTimeAndToolPrefix).toHaveBeenCalled();
        });
    });

    describe('handleChangeEndTime', () => {
        it('should not update startTime when startTime is before endTime', () => {
            // Arrange
            const setFieldValue = jest.fn();
            const startTime = '7/28/2021 2:26:28 PM';
            const endTime = '7/28/2021 2:26:29 PM';
            const container = shallow(<CreateForm {...defaultProps} />).instance();

            // Act
            container.handleChangeEndTime(setFieldValue, startTime, endTime);
            jest.runAllTimers();

            // Assert
            expect(setFieldValue).toHaveBeenCalledWith('endTime', endTime);
        });

        it('should update startTime when startTime is before endTime', () => {
            // Arrange
            const setFieldValue = jest.fn();
            const startTime = '7/28/2021 2:26:28 PM';
            const endTime = '7/28/2021 2:26:27 PM';
            DateTimeService.toShortDateTimeFormat = jest.fn(() => '7/28/2021 2:26:27 PM');
            const container = shallow(<CreateForm {...defaultProps} />).instance();

            // Act
            container.handleChangeEndTime(setFieldValue, startTime, endTime);
            jest.runAllTimers();

            // Assert
            expect(setFieldValue.mock.calls[0]).toEqual(['endTime', endTime]);
            expect(setFieldValue).toHaveBeenLastCalledWith('startTime', new Date('7/28/2021 2:25:27 PM'));
        });
    });
});