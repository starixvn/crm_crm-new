import React, { Component, Fragment } from 'react';
import { Button, Col, Form, Row, Collapse } from 'react-bootstrap';
import LangHelper from '@jsroot/common/langHelper';
import DatePicker from '@jsroot/components/date-picker/index';
import MultipleSelect from '@jsroot/components/multiple-select/index';
import OverlayTrigger from 'react-bootstrap/OverlayTrigger';
import Tooltip from 'react-bootstrap/Tooltip';
import VerifyCustomer from '@jsroot/components/verifyCustomer';
import CkEditor from '@jsroot/components/ckeditor/index';
import AutoComplete from '@jsroot/components/AutoComplete';
import { validateNoOfInquiry } from '../common.functions';

export default class FeedbackInfo extends Component {
    renderAutoGeneratedSection = () => {
        const { values, handleChange } = this.props;
        if (values.isPreviewDescription) {
            return null;
        }

        return (
            <div className="panel-group border-bottom-0">
                <Form.Group as={Row} className="panel-title">
                    <Form.Label>{LangHelper.getResource('AutoGenerated')}</Form.Label>
                </Form.Group>
                <div className="panel-content">
                    <Form.Control as="textarea" rows={3} className="shadow-none" name="autoGenerated"
                        value={values.autoGenerated} onChange={handleChange}
                    />
                </div>
            </div>
        );
    };

    renderDescriptionSection = () => {
        const { collapse, values, touched, errors, setFieldValue, onCollapseExpand } = this.props;
        return (
            <div className="panel-group border-bottom-0">
                <Form.Group as={Row} className={`panel-title justify-content-between ${collapse.description ? 'border-bottom-0' : ''}`}
                    onClick={() => onCollapseExpand('description')}
                    aria-controls="collapse-expand-description" aria-expanded={!collapse.description}
                >
                    <Form.Label className="required">{LangHelper.getResource('Description')}</Form.Label>
                    <span onClick={event => {
                        event.stopPropagation();
                        setFieldValue('isPreviewDescription', !values.isPreviewDescription);
                    }}
                    >
                        {LangHelper.getResource(values.isPreviewDescription ? 'Edit' : 'Preview')}
                    </span>
                </Form.Group>
                <Collapse in={!collapse.description}>
                    <div id="collapse-expand-description" className="panel-content">
                        {
                            values.isPreviewDescription &&
                            <Fragment>
                                <div style={{ whiteSpace: 'pre-line' }}>{values.autoGenerated}</div>
                                <div dangerouslySetInnerHTML={{ __html: values.description }} />
                            </Fragment>
                        }
                        {
                            !values.isPreviewDescription &&
                            <CkEditor isInvalid={touched.description && errors.description}
                                data={values.description} username={window.currentUsername}
                                onChange={value => setFieldValue('description', value)}
                            />
                        }
                    </div>
                </Collapse>
            </div>
        );
    };

    renderSolutionSection = () => {
        const { collapse, values, touched, errors, setFieldValue, onCollapseExpand } = this.props;
        return (
            <div className="panel-group border-bottom-0">
                <Form.Group as={Row} className={`panel-title justify-content-between ${collapse.solution ? 'border-bottom-0' : ''}`}
                    onClick={() => onCollapseExpand('solution')}
                    aria-controls="collapse-expand-solution" aria-expanded={!collapse.solution}
                >
                    <Form.Label className="required">{LangHelper.getResource('Solution')}</Form.Label>
                    <span onClick={event => {
                        event.stopPropagation();
                        setFieldValue('isPreviewSolution', !values.isPreviewSolution);
                    }}
                    >
                        {LangHelper.getResource(values.isPreviewSolution ? 'Edit' : 'Preview')}
                    </span>
                </Form.Group>
                <Collapse in={!collapse.solution}>
                    <div id="collapse-expand-solution" className="panel-content">
                        {
                            values.isPreviewSolution &&
                            <div dangerouslySetInnerHTML={{ __html: values.solution }} />
                        }
                        {
                            !values.isPreviewSolution &&
                            <CkEditor isInvalid={touched.solution && errors.solution}
                                data={values.solution} username={window.currentUsername}
                                onChange={value => setFieldValue('solution', value)}
                            />
                        }
                    </div>
                </Collapse>
            </div>
        );
    };

    renderReviewSection = () => {
        const { values, touched, errors, setFieldValue } = this.props;
        return (
            <div className="panel-group">
                <Form.Group as={Row} className="panel-title border-bottom-0">
                    <Form.Label className={values.isReviewed ? 'required' : ''}>{LangHelper.getResource('Review')}</Form.Label>
                    <input className="ml-2" type='checkbox'
                        onChange={event => setFieldValue('isReviewed', event.target.checked)}
                        checked={values.isReviewed}
                    />
                    <span className="font-italic ml-2">
                        {values.reviewerName ? LangHelper.formatString(LangHelper.getResource('ReviewerBy'), values.reviewerName, values.solveDate) : ''}
                    </span>
                </Form.Group>
                <Collapse in={values.isReviewed}>
                    <div className="panel-content">
                        <CkEditor isInvalid={touched.review && errors.review}
                            data={values.review} username={window.currentUsername}
                            onChange={value => setFieldValue('review', value)}
                        />
                    </div>
                </Collapse>
            </div>
        );
    };

    renderRoleSection = () => {
        const { values, touched, errors, setFieldValue, handleChange, settings, relatedCustomers, feedbackSubjectTemplates,
            onChangeCheckboxHasRelatedCustomer, onPasteCustomer, onVerifyRelatedCustomer, onDeleteCustomer, onGetFeedbackSubjectTemplates
        } = this.props;
        const { roles, countries } = settings;
        return (
            <div>
                <Form.Group as={Row}>
                    <Col sm="4" md="4">
                        <Form.Group as={Row}>
                            <Form.Label column sm="4" md="4" htmlFor="roleId">
                                {LangHelper.getResource('Role')}
                            </Form.Label>
                            <Col md="8" sm="8">
                                <Form.Control as="select" size="sm" className="shadow-none" id='roleId' name='roleId' value={values.roleId} onChange={handleChange}>
                                    {roles.map(item => <option key={item.id} value={item.id}>{item.value}</option>)}
                                </Form.Control>
                            </Col>
                        </Form.Group>
                    </Col>
                    <Col sm="4" md="4">
                        <Form.Group as={Row}>
                            <Form.Label column sm="4" md="4" htmlFor="countryId">
                                {LangHelper.getResource('Country')}
                            </Form.Label>
                            <Col sm="8" md="8">
                                <Form.Control as="select" size="sm" className="shadow-none"
                                    id="countryId" name="countryId"
                                    value={values.countryId} onChange={handleChange}
                                >
                                    {countries.map(item => <option key={item.id} value={item.id}>{item.name}</option>)}
                                </Form.Control>
                            </Col>
                        </Form.Group>
                    </Col>
                    <Col sm="4" md="4">
                        <Form.Group as={Row}>
                            <Form.Label column sm="4" md="4" htmlFor="noInquiries">
                                {LangHelper.getResource('NoOfInquiries')}
                            </Form.Label>
                            <Col sm="8" md="8">
                                <Form.Control size="sm" type="number" min={1} max={3200}
                                    value={values.noInquiries} id="noInquiries" name="noInquiries"
                                    className="shadow-none" autoComplete="off"
                                    onInput={validateNoOfInquiry} onChange={handleChange}
                                />
                            </Col>
                        </Form.Group>
                    </Col>
                </Form.Group>
                <Form.Group as={Row}>
                    <Col sm="3" md="3">
                        <Form.Group as={Row}>
                            <Col>
                                <div className="d-flex">
                                    <Form.Check type="checkbox" id="checkbox-related-customer" htmlFor="checkbox-related-customer"
                                        label={LangHelper.getResource('IsRelatedToCustomer')}
                                        checked={values.hasRelated}
                                        onChange={onChangeCheckboxHasRelatedCustomer}
                                    />
                                    <OverlayTrigger
                                        placement="bottom"
                                        overlay={
                                            <Tooltip id="tooltip-customers">
                                                {LangHelper.getResource('MultipleCustomersTooltip')}
                                            </Tooltip>
                                        }
                                    >
                                        <span className="fa fa-question-circle-o" />
                                    </OverlayTrigger>
                                </div>
                            </Col>
                        </Form.Group>
                    </Col>
                    <Col sm="7" md="7">
                        <Form.Group as={Row}>
                            <Col>
                                <Form.Control type="text" size="sm" className="shadow-none" autoComplete="off"
                                    name="customerNameInput"
                                    disabled={!values.hasRelated} value={values.customerNameInput}
                                    isInvalid={touched.customerNameInput && errors.customerNameInput}
                                    onPaste={event => onPasteCustomer(setFieldValue, event, values.customerNameInput)}
                                    onChange={handleChange}
                                />
                            </Col>
                        </Form.Group>
                    </Col>
                    <Col sm="2" md="2">
                        <Form.Group as={Row}>
                            <Col>
                                <Button type="button" variant="primary" size="sm"
                                    disabled={!values.customerNameInput}
                                    onClick={onVerifyRelatedCustomer}
                                >
                                    {LangHelper.getResource('Verify')}
                                </Button>
                            </Col>
                        </Form.Group>
                    </Col>
                </Form.Group>
                {
                    values.hasRelated && relatedCustomers.length > 0 &&
                    <div className="verify-customer">
                        <VerifyCustomer listOfCustomers={relatedCustomers} onClick={onDeleteCustomer} />
                    </div>
                }
                <Form.Group as={Row}>
                    <Col sm="3" md="3">
                        <Form.Group as={Row}>
                            <Form.Label column sm="4" md="4" htmlFor="subject" className="required">
                                {LangHelper.getResource('Subject')}
                            </Form.Label>
                        </Form.Group>
                    </Col>
                    <Col sm="9" md="9">
                        <Form.Group as={Row}>
                            <Col>
                                <AutoComplete isInvalid={touched.subject && errors.subject}
                                    value={values.subject}
                                    options={feedbackSubjectTemplates} displayField="subject"
                                    onChange={value => setFieldValue('subject', value)}
                                    onInputChange={onGetFeedbackSubjectTemplates}
                                />
                            </Col>
                        </Form.Group>
                    </Col>
                </Form.Group>
            </div>
        );
    };

    renderProductSection = () => {
        const { values, touched, errors, setFieldValue, handleChange, settings, productOptions, subProductOptions,
            betTypeOptions,onChangeProduct, onChangeSubProduct
        } = this.props;
        const { responses, languages, statuses } = settings;
        return (
            <div>
                <Form.Group as={Row}>
                    <Col md="4" sm="4">
                        <Form.Group as={Row}>
                            <Form.Label htmlFor="product" column sm="4" md="4">{LangHelper.getResource('Product')}</Form.Label>
                            <Col sm="8" md="8">
                                <MultipleSelect
                                    dataSource={productOptions}
                                    keyField='id' valueField='value'
                                    hasAllOption={productOptions.length > 0}
                                    isAllTextShown={productOptions.length > 0}
                                    hasSearchBox isNAOption
                                    maxDisplayItemCount={2}
                                    onChange={(currentItem, selectedItemsKey) => {
                                        onChangeProduct(setFieldValue, selectedItemsKey, values.subProductIds);
                                    }}
                                />
                            </Col>
                        </Form.Group>
                    </Col>
                    <Col sm="4" md="4">
                        <Form.Group as={Row}>
                            <Form.Label column sm="4" md="4" htmlFor="subProductIds">{LangHelper.getResource('SubProduct')}</Form.Label>
                            <Col md="8" sm="8">
                                <MultipleSelect
                                    isAllTextShown={subProductOptions.length > 0}
                                    hasSearchBox isNAOption
                                    maxDisplayItemCount={3}
                                    dataSource={subProductOptions}
                                    keyField='id' valueField='value'
                                    onChange={(currentItem, selectedItemsKey) => {
                                        onChangeSubProduct(setFieldValue, selectedItemsKey, values.betTypeIds);
                                    }}
                                    hasAllOption={subProductOptions.length > 0}
                                />
                            </Col>
                        </Form.Group>
                    </Col>
                    <Col md="4" sm="4">
                        <Form.Group as={Row}>
                            <Form.Label column md="4" sm="4" htmlFor="betTypeIds">{LangHelper.getResource('BetType')}
                            </Form.Label>
                            <Col sm="8" md="8">
                                <MultipleSelect
                                    hasSearchBox isNAOption
                                    keyField='id' valueField='value'
                                    hasAllOption={betTypeOptions.length > 0}
                                    maxDisplayItemCount={2}
                                    dataSource={betTypeOptions}
                                    isAllTextShown={betTypeOptions.length > 0}
                                    onChange={(currentItem, selectedItemsKey) => {
                                        setFieldValue('betTypeIds', selectedItemsKey);
                                    }}
                                />
                            </Col>
                        </Form.Group>
                    </Col>
                </Form.Group>
                <Form.Group as={Row}>
                    <Col sm="4" md="4">
                        <Form.Group as={Row}>
                            <Form.Label column sm="4" md="4" htmlFor="responseId">
                                {LangHelper.getResource('Response')}
                            </Form.Label>
                            <Col sm="8" md="8">
                                <Form.Control as="select" size="sm" className="shadow-none"
                                    id="responseId" name="responseId"
                                    value={values.responseId} onChange={handleChange}
                                >
                                    {responses.map(item => <option key={item.id} value={item.id}>{item.value}</option>)}
                                </Form.Control>
                            </Col>
                        </Form.Group>
                    </Col>
                    <Col sm="4" md="4">
                        <Form.Group as={Row}>
                            <Form.Label column sm="4" md="4" htmlFor="languageId" className="required">
                                {LangHelper.getResource('Language')}
                            </Form.Label>
                            <Col sm="8" md="8">
                                <Form.Control as="select" size="sm" className="shadow-none"
                                    isInvalid={touched.languageId && errors.languageId}
                                    id="languageId" name="languageId"
                                    value={values.languageId} onChange={handleChange}
                                >
                                    {languages.map(item => <option key={item.languageId} value={item.languageId}>{item.name}</option>)}
                                </Form.Control>
                            </Col>
                        </Form.Group>
                    </Col>
                    <Col sm="4" md="4">
                        <Form.Group as={Row}>
                            <Form.Label column sm="4" md="4" htmlFor="statusId">
                                {LangHelper.getResource('Status')}
                            </Form.Label>
                            <Col sm="8" md="8">
                                <Form.Control as="select" size="sm" className="shadow-none"
                                    id="statusId" name="statusId"
                                    value={values.statusId} onChange={handleChange}
                                >
                                    {statuses.map(item => <option key={item.statusId} value={item.statusId}>{item.name}</option>)}
                                </Form.Control>
                            </Col>
                        </Form.Group>
                    </Col>
                </Form.Group>
            </div>
        );
    };

    render() {
        const { collapse, values, touched, errors,
            extensionOptions, communicationToolOptions, mainCategoryOptions, subCategoryOptions,
            setFieldValue, onCollapseExpand, onChangeMainCategory
        } = this.props;

        return (
            <>
                <div className="panel-group border-bottom-0 border-top-0">
                    <Form.Group as={Row} className="panel-title border-bottom-0" onClick={() => onCollapseExpand('details')}
                        aria-controls="collapse-expand-details"
                        aria-expanded={!collapse.details}
                    >
                        <Form.Label>{LangHelper.getResource('Details')}</Form.Label>
                    </Form.Group>
                    <Collapse in={!collapse.details}>
                        <div id="collapse-expand-details" className="panel-content border-bottom-0">
                            <Form.Group as={Row}>
                                <Col sm="4" md="4">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="feedbackDate">
                                            {LangHelper.getResource('FeedbackDate')}
                                        </Form.Label>
                                        <Col sm="8" md="8">
                                            <div className='react-datepicker-wrapper-container form-control-wrapper'>
                                                <DatePicker timeInputLabel="Time:" showTimeInput
                                                    selected={values.feedbackDate}
                                                    onChange={value => setFieldValue('feedbackDate', value)}
                                                />
                                            </div>
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="4" md="4">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="resolutionDate">
                                            {LangHelper.getResource('ResolutionTime')}
                                        </Form.Label>
                                        <Col sm="8" md="8">
                                            <div className='react-datepicker-wrapper-container form-control-wrapper'>
                                                <DatePicker timeInputLabel="Time:" showTimeInput
                                                    selected={values.resolutionDate}
                                                    onChange={value => setFieldValue('resolutionDate', value)}
                                                />
                                            </div>
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="4" md="4">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="extensionIds">
                                            {LangHelper.getResource('Station')}
                                        </Form.Label>
                                        <Col sm="8" md="8">
                                            <MultipleSelect
                                                dataSource={extensionOptions}
                                                keyField='id' valueField='value'
                                                hasAllOption={extensionOptions.length > 0}
                                                isAllTextShown={extensionOptions.length > 0}
                                                hasSearchBox isNAOption
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    setFieldValue('extensionIds', selectedItemsKey);
                                                }}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="4" md="4">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="communicationToolId" className="required">
                                            {LangHelper.getResource('Communication')}
                                        </Form.Label>
                                        <Col sm="8" md="8">
                                            <MultipleSelect
                                                isInvalid={touched.communicationToolIds && errors.communicationToolIds}
                                                dataSource={communicationToolOptions}
                                                keyField='id' valueField='name'
                                                hasAllOption={communicationToolOptions.length > 0}
                                                isAllTextShown={communicationToolOptions.length > 0}
                                                hasSearchBox isNAOption
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    setFieldValue('communicationToolIds', selectedItemsKey);
                                                }}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="4" md="4">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="mainCategoryIds" className="required">
                                            {LangHelper.getResource('Category')}
                                        </Form.Label>
                                        <Col sm="8" md="8">
                                            <MultipleSelect
                                                isInvalid={touched.mainCategoryIds && errors.mainCategoryIds}
                                                dataSource={mainCategoryOptions}
                                                keyField='mainCategoryID' valueField='name'
                                                hasAllOption={mainCategoryOptions.length > 0}
                                                isAllTextShown={mainCategoryOptions.length > 0}
                                                hasSearchBox isNAOption
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    onChangeMainCategory(setFieldValue, selectedItemsKey, values.subCategoryIds, values.subject);
                                                }}
                                                maxDisplayItemCount={1}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="4" md="4">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="subCategoryIds" className="required">
                                            {LangHelper.getResource('SubCategory')}
                                        </Form.Label>
                                        <Col sm="8" md="8">
                                            <MultipleSelect
                                                hasAllOption={subCategoryOptions.length > 0}
                                                isAllTextShown={subCategoryOptions.length > 0}
                                                isInvalid={touched.subCategoryIds && errors.subCategoryIds}
                                                dataSource={subCategoryOptions}
                                                hasSearchBox isNAOption
                                                maxDisplayItemCount={1}
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    setFieldValue('subCategoryIds', selectedItemsKey);
                                                }}
                                                keyField='subCategoryId' valueField='name'
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            { this.renderProductSection() }
                            { this. renderRoleSection() }
                        </div>
                    </Collapse>
                </div>
                {this.renderAutoGeneratedSection()}
                {this.renderDescriptionSection()}
                {this.renderSolutionSection()}
                {this.renderReviewSection()}
            </>
        );
    }
}