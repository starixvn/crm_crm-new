import React, { PureComponent, Fragment } from 'react';
import CkEditor from '@jsroot/components/ckeditor/index';
import { Form, Row, Collapse } from 'react-bootstrap';
import LangHelper from '@jsroot/common/langHelper';

export default class CommentInfo extends PureComponent {

  renderAutoGeneratedSection = () => {
      const { values, handleChange } = this.props;
      if (values.isPreviewDescription) {
          return null;
      }

      return (
          <div className="panel-group border-bottom-0">
              <Form.Group as={Row} className="panel-title">
                  <Form.Label>{LangHelper.getResource('AutoGenerated')}</Form.Label>
              </Form.Group>
              <div className="panel-content">
                  <Form.Control as="textarea" rows={3} className="shadow-none" name="autoGenerated"
                      value={values.autoGenerated} onChange={handleChange}
                  />
              </div>
          </div>
      );
  };

    renderDescriptionSection = currentUsername => {
      const { collapse, values, touched, errors, setFieldValue, onCollapseExpand } = this.props;
      return (
          <div className="panel-group border-bottom-0">
              <Form.Group as={Row} className={`panel-title justify-content-between ${collapse.description ? 'border-bottom-0' : ''}`}
                  onClick={() => onCollapseExpand('description')}
                  aria-controls="collapse-expand-description" aria-expanded={!collapse.description}
              >
                  <Form.Label className="required">{LangHelper.getResource('Description')}</Form.Label>
                  <span onClick={event => {
                      event.stopPropagation();
                      setFieldValue('isPreviewDescription', !values.isPreviewDescription);
                  }}
                  >
                      {LangHelper.getResource(values.isPreviewDescription ? 'Edit' : 'Preview')}
                  </span>
              </Form.Group>
              <Collapse in={!collapse.description}>
                  <div id="collapse-expand-description" className="panel-content">
                      {
                          values.isPreviewDescription &&
                          <Fragment>
                              <div style={{ whiteSpace: 'pre-line' }}>{values.autoGenerated}</div>
                              <br/>
                              <div dangerouslySetInnerHTML={{ __html: values.description }} />
                          </Fragment>
                      }
                      {
                          !values.isPreviewDescription &&
                          <CkEditor isInvalid={touched.description && errors.description}
                              data={values.description} username={currentUsername}
                              onChange={value => setFieldValue('description', value)}
                          />
                      }
                  </div>
              </Collapse>
          </div>
      );
  };

  renderSolutionSection = currentUsername => {
      const { collapse, values, touched, errors, setFieldValue, onCollapseExpand } = this.props;
      return (
          <div className="panel-group border-bottom-0">
              <Form.Group as={Row} className={`panel-title justify-content-between ${collapse.solution ? 'border-bottom-0' : ''}`}
                  onClick={() => onCollapseExpand('solution')}
                  aria-controls="collapse-expand-solution" aria-expanded={!collapse.solution}
              >
                  <Form.Label className="required">{LangHelper.getResource('Solution')}</Form.Label>
                  <span onClick={event => {
                      event.stopPropagation();
                      setFieldValue('isPreviewSolution', !values.isPreviewSolution);
                  }}
                  >
                      {LangHelper.getResource(values.isPreviewSolution ? 'Edit' : 'Preview')}
                  </span>
              </Form.Group>
              <Collapse in={!collapse.solution}>
                  <div id="collapse-expand-solution" className="panel-content">
                      {
                          values.isPreviewSolution &&
                          <div dangerouslySetInnerHTML={{ __html: values.solution }} />
                      }
                      {
                          !values.isPreviewSolution &&
                          <CkEditor isInvalid={touched.solution && errors.solution}
                              data={values.solution} username={currentUsername}
                              onChange={value => setFieldValue('solution', value)}
                          />
                      }
                  </div>
              </Collapse>
          </div>
      );
  };

  renderReviewSection = currentUsername => {
      const { values, touched, errors, setFieldValue } = this.props;
      return (
          <div className="panel-group">
              <Form.Group as={Row} className="panel-title border-bottom-0">
                  <Form.Label className={values.isReviewed ? 'required' : ''}>{LangHelper.getResource('Review')}</Form.Label>
                  <input className="ml-2" type='checkbox'
                      onChange={event => setFieldValue('isReviewed', event.target.checked)}
                      checked={values.isReviewed}
                  />
                  <span className="font-italic ml-2">
                      {values.reviewerName ? LangHelper.formatString(LangHelper.getResource('ReviewerBy'), values.reviewerName, values.solveDate) : ''}
                  </span>
              </Form.Group>
              <Collapse in={values.isReviewed}>
                  <div className="panel-content">
                      <CkEditor isInvalid={touched.review && errors.review}
                          data={values.review} username={currentUsername}
                          onChange={value => setFieldValue('review', value)}
                      />
                  </div>
              </Collapse>
          </div>
      );
  };
  render() {
    const currentUsername = window.currentUsername;
    return (
      <Fragment>
        {this.renderAutoGeneratedSection()}
        {this.renderDescriptionSection(currentUsername)}
        {this.renderSolutionSection(currentUsername)}
        {this.renderReviewSection(currentUsername)}
      </Fragment>
    );
  }
}