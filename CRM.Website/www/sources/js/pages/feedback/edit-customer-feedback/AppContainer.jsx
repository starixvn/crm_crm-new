    async componentDidMount() {
        let custId = 0;
        Site.blockUI();
        const url = Site.resolveClientUrl(`Feedback/GetCustomerFeedbackById/${this.props.feedbackId}`);
        await DataService.getDataAsync(url).then(response => {
            const data = response.data;
            custId = data.feedback.custId;
            const feedbackSettings = this.getFeedbackSettings(data.feedback, data.settings);
            const relatedCustomers = data.feedback.relatedCustomers.map(customer => {
                return {
                    custId: customer.custId,
                    val: customer.username,
                    isSiteActive: customer.isSiteActive,
                    isLicensee: customer.isLicensee,
                    isAuthorized: customer.isAuthorized
                };
            });
            const extensionOptions = data.settings.extensions.map(item => {
                return {
                    id: item.id,
                    value: item.value,
                    checked: feedbackSettings.extensionIds.includes(item.id)
                };
            });
            const communicationToolOptions = data.settings.communicationTools.map(item => {
                return {
                    id: item.id,
                    name: item.name,
                    checked: feedbackSettings.communicationToolIds.includes(item.id)
                };
            });
            const mainCategoryOptions = data.settings.mainCategories.map(item => {
                return {
                    mainCategoryID: item.mainCategoryID,
                    name: item.name,
                    checked: feedbackSettings.mainCategoryIds.includes(item.mainCategoryID)
                };
            });

            const mainCategoryIds = feedbackSettings.mainCategoryIds.join(',').split(',');
            const subCategoryIds = feedbackSettings.subCategoryIds.join(',').split(',');
            const subCategoryOptions = getSubCategories(mainCategoryIds, data.settings.subCategories, subCategoryIds, false);

            const productOptions = data.settings.products.map(item => {
                return {
                    id: item.id,
                    value: item.value,
                    checked: feedbackSettings.productIds.includes(item.id)
                };
            });
            const subProducts = data.settings.subProducts.filter(item => feedbackSettings.productIds.includes(item.parentId) && item.parentId !== 0);
            const subProductOptions = subProducts.map(item => {
                return {
                    id: item.id,
                    value: item.value,
                    checked: feedbackSettings.subProductIds.includes(item.id)
                };
            });
            const bettypes = data.settings.bettypes.filter(item => feedbackSettings.subProductIds.includes(item.parentId) && item.parentId !== 0);
            const betTypeDistinct = bettypes.filter((v, i, a) => a.findIndex(t => t.id === v.id) === i);
            const betTypeOptions = betTypeDistinct.map(item => {
                return {
                    id: item.id,
                    value: item.value,
                    checked: feedbackSettings.betTypeIds.includes(item.id)
                };
            });

            this.setState({
                feedback: this.initFormikData(data.feedback, data.settings),
                fieldInput: this.initCustomerData(data.feedback, data.settings),
                originalLatestFeedbackCommunicationTools: this.getLatestFeedbackCommunicationTools(data.feedback.latestFeedbackCommunicationTools),
                oldReLatedCust: relatedCustomers,
                settings: data.settings,
                hasReviewFeedbackPermission: data.hasReviewFeedbackPermission,
                extensionOptions,
                communicationToolOptions,
                mainCategoryOptions,
                subCategoryOptions,
                productOptions,
                subProductOptions,
                betTypeOptions,
                relatedCustomers
            });
        }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);

        await DataService.getDataAsync(Site.resolveClientUrl(`AccountDetail/GetSettingPicCommunicationTools`)).then(response => {
            this.setState({settingCommunicationTool: response.data});
        }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);

        await DataService.postDataAsync(Site.resolveClientUrl(`AccountDetail/GetCustomerById`), { customerId: custId }).then(response => {
            this.setState({ customerInfo: response.data });
        }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);

        getPermission(FunctionKey.HeadlineInfo, true).then(response => {
            this.setState({ headlineInfoPolicy: response });
        });
    }

