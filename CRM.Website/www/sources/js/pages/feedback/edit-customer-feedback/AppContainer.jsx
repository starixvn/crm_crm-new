    handlePasteCustomer = (event, customerNameInput) => {
        const customer = customerNameInput?.trim();
        this.setState({editResult: null});
        const items = (event.clipboardData || window.clipboardData).getData('text')
            .replace(/ /g, ',')
            .replace(/\r\n/g, ',')
            .replace(/\n/g, ',')
            .replace(/\t/g, ',')
            .split(',').filter(item => item !== '');

        setTimeout(() => {
            const customerInput = (customer && customer.length > 0 ? customer + ',' : '').concat(items.join(','));
            this.setState({
                fieldInput: {
                    ...this.state.fieldInput,
                    customerNameInput: customerInput
                }
            });
        }, 100);
    };

    isValidCustomer = customers => {
        return customers.split(',').filter(function (value) {
            return value.length > 50;
        }).length === 0;
    };

    handleVerifyRelatedCustomer = async event => {
        event.preventDefault();
        const regex1 = new RegExp(/,\s+/g),
            regex2 = new RegExp(/^,+|,+$/g),
            regex3 = new RegExp(/,{2,}/g);
        const formikValues = this.formik.values;

        const customersInput = this.state.fieldInput.customerNameInput.trim().replace(regex1, ',') // NOSONAR
            .replace(regex2, '') // NOSONAR
            .replace(regex3, ','); // NOSONAR

        if (this.isValidCustomer(customersInput)) {
            this.formik.errors.customerNameInput = '';
            this.setState({editResult:null});
            const url = Site.resolveClientUrl('CustomerSetting/VerifyUsername');
            await DataService.postDataAsync(url, { username: customersInput }).then(response => {
                let customers = [...this.state.relatedCustomers, ...response.data];
                customers = customers.filter((v, i, a) => a.findIndex(t => t.custId === v.custId && t.val === v.val) === i);
                this.setState({
                    relatedCustomers: customers
                });

                const autoGenerated = updateAutoGeneratedCustomerPrefix(formikValues.hasRelated, customers, formikValues.autoGenerated);

                this.formik.setFieldValue('autoGenerated', autoGenerated);
                this.setState({customerNameInput:''});
                this.setState({
                    fieldInput: {
                        ...this.state.fieldInput,
                        customerNameInput: ''
                    }
                });
            });
        } else {
            this.formik.errors.customerNameInput = 'Customer Name must not over 50 characters long!';
        }
    };

