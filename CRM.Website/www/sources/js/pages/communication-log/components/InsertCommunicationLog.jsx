import React, { Component, Fragment } from 'react';
import { connect } from 'react-redux';
import { ActionCreators } from '../actions';
import { bindActionCreators } from 'redux';
import { Formik } from 'formik';
import moment from 'moment';
import { Button, Form, Modal, Row, Col, Collapse } from 'react-bootstrap';
import CkEditor from '@jsroot/components/ckeditor/index';
import MultipleSelect from '@jsroot/components/multiple-select/index';
import DatePicker from '@jsroot/components/date-picker/index';
import AutoComplete from '@jsroot/components/AutoComplete';
import SelectWithSearch from '@jsroot/components/SelectWithSearch';
import DraggableModalDialog from '@jsroot/components/DraggableModalDialog';
import FormikErrorMessage from '@jsroot/components/FormikErrorMessage';
import LangHelper from '@jsroot/common/langHelper';
import ResponseMessage from '@jsroot/components/ResponseMessage';
import VerifyCustomer from '@jsroot/components/verifyCustomer';
import SweetModalDialog from '@jsroot/components/SweetModalDialog';
import DateTimeService from '@jsroot/common/dateTimeService';
import Site from '@jsroot/common/site';
import { validateNoOfInquiry } from '../../feedback/common.functions';
import {
    getProductParams, getCategoryParams, generateTimeAndToolPrefix, updateAutoGeneratedCustomerPrefix
} from '@jsroot/common/shareScripts';
import {
    handleChangeMainCategory, handleChangeProduct, handleChangeSubProduct, validateFormik,
    handlePasteCustomer, handleGetFeedbackSubjectTemplates, isValidCustomer
} from '../common.functions';

export class InsertCommunicationLog extends Component {

    constructor(props) {
        super(props);

        this.state = {
            collapse: {
                autoGenerated: false,
                remark: false,
                solution: false
            },
            latestCommunicationTool: 'N/A',
            subCategories: [],
            subProducts: [],
            betTypes: [],
            relatedCustomers: [],
            confirmInsertDialog: { show: false },
            checkDuplicateDialog: { show: false },
            insertResult: null
        };
    }

    async componentDidMount(){
        await this.props.getInsertSettings();
    }

    initFormData = () => {
        const insertSettings = this.props.insertSettings;
        const startTime = new Date(DateTimeService.toShortDateTimeFormat(new Date(window.currentClientTime)));
        const endTime = new Date(DateTimeService.toShortDateTimeFormat(new Date(window.currentClientTime)));
        endTime.setMinutes(endTime.getMinutes() + 1);

        return {
            customerNameInput: '',
            startTime,
            endTime,
            extensionIds: insertSettings.extensions[0].id.toString(),
            languageId: insertSettings.languages[1].languageId,
            countryId: insertSettings.countries[0].id,
            communicationToolIds: '',
            mainCategoryIds: '',
            subCategoryIds: '',
            productIds: '',
            subProductIds: '',
            betTypeIds: '',
            statusId: insertSettings.statuses[0].statusId,
            roleId: insertSettings.roles[4].id,
            siteId: 0,
            licenseeTypeId: insertSettings.licenseeTypes[0].id,
            responseId: insertSettings.responses[0].id,
            noOfInquiries: '',
            subject: '',
            autoGenerated: generateTimeAndToolPrefix(startTime, this.state.latestCommunicationTool) + ' \nSystem ID: ',
            remark: '',
            solution: ''
        };
    };

    handleChangeStartTime = (setFieldValue, startTime, endTime) => {
        setFieldValue('startTime', startTime);
        if (moment(startTime).isAfter(moment(endTime))) {
            endTime = new Date(DateTimeService.toShortDateTimeFormat(new Date(startTime)));
            endTime.setMinutes(endTime.getMinutes() + 1);

            setFieldValue('endTime', endTime);
        }
        setTimeout(() => this.updateTimeAndToolPrefix(), 100);
    };

    handleChangeEndTime = (setFieldValue, startTime, endTime) => {
        setFieldValue('endTime', endTime);

        if (moment(startTime).isAfter(moment(endTime))) {
            startTime = new Date(DateTimeService.toShortDateTimeFormat(new Date(endTime)));
            startTime.setMinutes(startTime.getMinutes() - 1);

            setFieldValue('startTime', startTime);
        }
    };

    updateTimeAndToolPrefix = () => {
        const formikValues = this.formik.values;
        const relatedCustomers = this.state.relatedCustomers.filter(item => item.custId !== 0).map(item => item.val).join(', ');

        const newTimeAndToolPrefix = generateTimeAndToolPrefix(
            formikValues.startTime,
            this.state.latestCommunicationTool);
        const autoGenerated = `${newTimeAndToolPrefix} \nSystem ID: ${relatedCustomers}`;
        this.formik.setFieldValue('autoGenerated', autoGenerated);
    };

    handleChangeCommunicationTool = (setFieldValue, currentItem, selectedItemsKey) => {
        setFieldValue('communicationToolIds', selectedItemsKey);

        const communicationTools = this.props.insertSettings.communicationTools;
        let latestCommunicationTool = '';
        if (currentItem !== null && selectedItemsKey !== '') {
            latestCommunicationTool = currentItem.name;
        } else if (currentItem === null && selectedItemsKey !== '') {
            latestCommunicationTool = communicationTools[0].name;
        } else {
            if (selectedItemsKey !== '') {
                const communicationToolId = parseInt(selectedItemsKey.split(',')[0], 10);
                latestCommunicationTool = communicationTools.filter(x => x.id === communicationToolId)[0].name;
            }
        }

        this.setState({ latestCommunicationTool }, () => {
            setTimeout(() => this.updateTimeAndToolPrefix(), 100);
        });
    };

    setStateSubcategory = subCategories => {
        this.setState({ subCategories: subCategories });
    };

    setStateSubProduct = subProducts => {
        this.setState({ subProducts: subProducts });
    };

    setStateBetType = betTypes => {
        this.setState({ betTypes: betTypes });
    };

    handleVerifyInsertRelatedCustomer = () => {
        const formikValues = this.formik.values;
        const customersInput = formikValues.customerNameInput.trim()
                                .replace(/,\s+/g, ',').replace(/^,+|,+$/g, '').replace(/,{2,}/g, ',');
        if (isValidCustomer(customersInput)) {
            this.formik.errors.customerNameInput = '';
            this.props.verifyCustomers({ username: customersInput }).then(response => {
                let insertCustomers = [...this.state.relatedCustomers, ...response.data];
                insertCustomers = insertCustomers.filter((v, i, a) => a.findIndex(t => t.custId === v.custId && t.val === v.val) === i);
                this.setState({ relatedCustomers: insertCustomers });

                const updateAutoGenerated = updateAutoGeneratedCustomerPrefix(true, insertCustomers, formikValues.autoGenerated);
                this.formik.setFieldValue('autoGenerated', updateAutoGenerated);
                this.formik.setFieldValue('customerNameInput', '');
            });
        } else {
            this.formik.errors.customerNameInput = 'Customer Name must not over 50 characters long!';
        }
    };

    deleteVerifyInsertCustomer = idRelatedCustomer => {
        const insertRelated = this.state.relatedCustomers.filter(item => item.custId !== idRelatedCustomer);
        this.setState({ relatedCustomers: insertRelated });

        const updateAutoGenerated = updateAutoGeneratedCustomerPrefix(true, insertRelated, this.formik.values.autoGenerated);
        this.formik.setFieldValue('autoGenerated', updateAutoGenerated);
    };

    handleCollapseExpand = section => {
        this.setState(prevState => ({ collapse: { ...prevState.collapse, [section]: !prevState.collapse[section] } }));
    };

    confirmInsert = params => {
        this.setState({
            confirmInsertDialog: { show: true, params }
        });
    };

    handleSubmit = (values, { setSubmitting }) => {
        setSubmitting(true);
        const { insertSettings } = this.props;
        const { relatedCustomers } = this.state;
        const mainCategoryIds = [...new Set(values.mainCategoryIds.split(','))];
        const productIds = values.productIds ? [...new Set(values.productIds.split(','))] : [insertSettings.productNA.id];

        const params = {
            customerId: 1754,
            startTime: DateTimeService.toLongDateTimeFormat(DateTimeService.toServerDateTime(values.startTime)),
            endTime: DateTimeService.toLongDateTimeFormat(DateTimeService.toServerDateTime(values.endTime)),
            extensionIds: values.extensionIds !== '' ? values.extensionIds : insertSettings.extensionNA.id,
            communicationToolIds: values.communicationToolIds,
            products: getProductParams(productIds.length > 0 ? productIds : [],
                values.subProductIds.length > 0 ? values.subProductIds.split(',') : [],
                values.betTypeIds.length > 0 ? values.betTypeIds.split(',') : [], insertSettings),
            categories: getCategoryParams(mainCategoryIds, values.subCategoryIds.split(','), insertSettings.subCategories),
            relatedCustomerIds: relatedCustomers.filter(item => item.custId !== 0).map(item => item.custId).join(','),
            languageId: parseInt(values.languageId, 10),
            siteId: values.siteId,
            responseId: values.responseId,
            licenseeTypeId: values.licenseeTypeId,
            countryId: values.countryId,
            statusId: values.statusId,
            roleId: values.roleId,
            noInquiries: values.noInquiries,
            subject: values.subject,
            description: values.remark,
            autoGenerated: values.autoGenerated,
            solution: values.solution
        };

        this.confirmInsert(params);
    };

    handleCloseConfirmInsertDialog = () => {
        this.setState({
            confirmInsertDialog: { show: false }
        });
        this.formik.setSubmitting(false);
    };

    handleInsertLog = () => {
        Site.blockUI();
        const { params } = this.state.confirmInsertDialog;
        this.props.insertCommunicationLog(params).then(response => {
            Site.unblockUI();
            this.setState({ insertResult: response.data, confirmInsertDialog: { show: false } });
            if (response.data.isSuccessful) {
                setTimeout(() => {
                    this.props.onClose(true);
                }, 3000);
            } else {
                this.formik.setSubmitting(false);
            }
        });
    };

    handleCheckDuplicate = async () => {
        const { params } = this.state.confirmInsertDialog;
        await this.props.checkFeedbackDuplication({
            customerId: params.customerId,
            categories: params.categories,
            startTime: params.startTime
        });

        if (this.props.duplicateFeedbackId === 0) {
            this.handleInsertLog();
        } else {
            this.setState({ checkDuplicateDialog: {show: true} });
        }
    };

    handleCloseCheckDuplicateDialog = () => {
        this.setState({ checkDuplicateDialog: { show: false } });
        this.setState({ confirmInsertDialog: { show: false } });
        this.formik.setSubmitting(false);
    };

    renderForm = ({
        values,
        errors,
        touched,
        handleChange,
        handleSubmit,
        setFieldValue,
        isSubmitting
    }) => {
        const { collapse, subCategories, subProducts, betTypes, insertResult, relatedCustomers } = this.state;
        const { insertSettings, feedbackSubjectTemplates } = this.props;
        const { extensions, countries, communicationTools, languages, mainCategories, products, statuses, responses, roles, sites, licenseeTypes } = insertSettings;

        return (
            <Form noValidate onSubmit={handleSubmit}>
                <Modal.Body>
                    <FormikErrorMessage touched={touched} errors={errors} fieldNames={Object.keys(values)} />
                    {
                        insertResult &&
                        <ResponseMessage isSuccessful={insertResult.isSuccessful}
                            message={insertResult.message || LangHelper.getResource('CreateMultipleLogsSuccessfully')}
                        />
                    }
                    <div className="panel-group border-bottom-0">
                        <div className="panel-content">
                            <Form.Group as={Row}>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="startTime">{LangHelper.getResource('StartTime')}</Form.Label>
                                        <Col sm="6" md="6" className="react-datepicker-wrapper-container form-control-wrapper">
                                            <DatePicker isInvalid={touched.startTime && errors.startTime}
                                                timeInputLabel="Time:"
                                                showTimeInput
                                                selected={values.startTime}
                                                onChange={value => this.handleChangeStartTime(setFieldValue, value, values.endTime)}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="ext">Ext</Form.Label>
                                        <Col sm="6" md="6">
                                            <MultipleSelect
                                                keyField='id' valueField='value'
                                                hasSearchBox isNAOption
                                                dataSource={extensions}
                                                hasAllOption={extensions.length > 0}
                                                isAllTextShown={extensions.length > 0}
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    setFieldValue('extensionIds', selectedItemsKey);
                                                }}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="endTime">{LangHelper.getResource('EndTime')}</Form.Label>
                                        <Col sm="6" md="6" className="react-datepicker-wrapper-container form-control-wrapper">
                                            <DatePicker
                                                timeInputLabel="Time:"
                                                showTimeInput
                                                selected={values.endTime}
                                                onChange={value => this.handleChangeEndTime(setFieldValue, values.startTime, value)}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="response">{LangHelper.getResource('Response')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <Form.Control as="select" size="sm" className="shadow-none"
                                                id="responseId" name="responseId"
                                                value={values.responseId} onChange={handleChange}
                                            >
                                                {responses.map(item => <option key={item.id} value={item.id}>{item.value}</option>)}
                                            </Form.Control>
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="communicationToolId" className="required">{LangHelper.getResource('Communication')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <MultipleSelect
                                                isInvalid={touched.communicationToolIds && errors.communicationToolIds}
                                                dataSource={communicationTools}
                                                keyField='id' valueField='name'
                                                hasAllOption={communicationTools.length > 0}
                                                isAllTextShown={communicationTools.length > 0}
                                                hasSearchBox isNAOption
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    this.handleChangeCommunicationTool(setFieldValue, currentItem, selectedItemsKey);
                                                }}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="language" className="required">{LangHelper.getResource('Language')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <Form.Control as="select" size="sm" isInvalid={touched.languageId && errors.languageId}
                                                className="shadow-none" id="languageId" name="languageId"
                                                value={values.languageId} onChange={handleChange}
                                            >
                                                {languages.map(item => <option key={item.languageId} value={item.languageId}>{item.name}</option>)}
                                            </Form.Control>
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="mainCategory" className="required">{LangHelper.getResource('Category')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <MultipleSelect
                                                isInvalid={touched.mainCategoryIds && errors.mainCategoryIds}
                                                dataSource={mainCategories}
                                                keyField='mainCategoryID' valueField='name'
                                                hasAllOption={mainCategories.length > 0}
                                                isAllTextShown={mainCategories.length > 0}
                                                hasSearchBox isNAOption
                                                maxDisplayItemCount={1}
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    handleChangeMainCategory(setFieldValue, selectedItemsKey, values.subCategoryIds, values.subject, insertSettings, this.setStateSubcategory);
                                                }}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="subCategory" className="required">{LangHelper.getResource('SubCategory')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <MultipleSelect
                                                isInvalid={touched.subCategoryIds && errors.subCategoryIds}
                                                dataSource={subCategories}
                                                keyField='subCategoryId' valueField='name'
                                                hasAllOption={subCategories.length > 0}
                                                isAllTextShown={subCategories.length > 0}
                                                hasSearchBox isNAOption
                                                maxDisplayItemCount={1}
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    setFieldValue('subCategoryIds', selectedItemsKey);
                                                }}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="product">{LangHelper.getResource('Product')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <MultipleSelect
                                                dataSource={products}
                                                keyField='id' valueField='value'
                                                hasAllOption={products.length > 0}
                                                isAllTextShown={products.length > 0}
                                                hasSearchBox isNAOption
                                                maxDisplayItemCount={1}
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    handleChangeProduct(setFieldValue, selectedItemsKey,
                                                        values.subProductIds, insertSettings, this.setStateSubProduct, this.setStateBetType);
                                                }}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="subProduct">{LangHelper.getResource('SubProduct')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <MultipleSelect
                                                dataSource={subProducts}
                                                keyField='id' valueField='value'
                                                hasAllOption={subProducts.length > 0}
                                                isAllTextShown={subProducts.length > 0}
                                                hasSearchBox isNAOption
                                                maxDisplayItemCount={1}
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    handleChangeSubProduct(setFieldValue, selectedItemsKey,
                                                        values.betTypeIds, insertSettings, this.setStateBetType);
                                                }}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="status">{LangHelper.getResource('Status')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <Form.Control as="select" size="sm" className="shadow-none"
                                                name="statusId" id="statusId" 
                                                value={values.statusId} onChange={handleChange}
                                            >
                                                {statuses.map(item => <option key={item.statusId} value={item.statusId}>{item.name}</option>)}
                                            </Form.Control>
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="betType">{LangHelper.getResource('BetType')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <MultipleSelect
                                                dataSource={betTypes}
                                                keyField='id' valueField='value'
                                                hasAllOption={betTypes.length > 0}
                                                isAllTextShown={betTypes.length > 0}
                                                hasSearchBox isNAOption
                                                maxDisplayItemCount={1}
                                                onChange={(currentItem, selectedItemsKey) => {
                                                    setFieldValue('betTypeIds', selectedItemsKey);
                                                }}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="role">{LangHelper.getResource('Role')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <Form.Control as="select" size="sm" className="shadow-none"
                                                id='roleId' name='roleId'
                                                value={values.roleId} onChange={handleChange}
                                            >
                                                {roles.map(item => <option key={item.id} value={item.id}>{item.value}</option>)}
                                            </Form.Control>
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="site">{LangHelper.getResource('Site')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <SelectWithSearch className='basic-single'
                                                OnChangeValue={value => setFieldValue('siteId', value.id)}
                                                options={sites}
                                                value={values.siteId}
                                                isHideNA={false}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="country">{LangHelper.getResource('Country')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <Form.Control as="select" size="sm" className="shadow-none"
                                                id="countryId" name="countryId"
                                                value={values.countryId} onChange={handleChange}
                                            >
                                                {countries.map(item => <option key={item.id} value={item.id}>{item.name}</option>)}
                                            </Form.Control>
                                        </Col>
                                    </Form.Group>
                                </Col>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="licenseeType">{LangHelper.getResource('LicenseeType')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <Form.Control as="select" size="sm" className="shadow-none" value={values.licenseeTypeId}
                                                id="licenseeTypeId" name="licenseeTypeId" onChange={handleChange}
                                            >
                                                {licenseeTypes.map(item => <option key={item.id} value={item.id}>{item.name}</option>)}
                                            </Form.Control>
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="6" md="6">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="4" md="4" htmlFor="noOfInquiries">{LangHelper.getResource('NoOfInquiries')}</Form.Label>
                                        <Col sm="6" md="6">
                                            <Form.Control size="sm" type="number" id="noInquiries" name="noInquiries"
                                                value={values.noInquiries} min={1} max={3200} className="shadow-none" autoComplete="off"
                                                onInput={validateNoOfInquiry} onChange={handleChange}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="12" md="12">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="2" md="2" htmlFor="relatedTo">{LangHelper.getResource('RelatedTo')}</Form.Label>
                                        <Col sm="8" md="8">
                                            <Form.Control type="text" size="sm" className="shadow-none" autoComplete="off"
                                                name="customerNameInput"
                                                value={values.customerNameInput}
                                                isInvalid={touched.customerNameInput && errors.customerNameInput}
                                                onPaste={event => handlePasteCustomer(setFieldValue, event, values.customerNameInput)}
                                                onChange={handleChange}
                                            />
                                        </Col>
                                        <Col sm="2" md="2">
                                            <Button type="button" variant="primary" size="sm"
                                                disabled={!values.customerNameInput}
                                                onClick={this.handleVerifyInsertRelatedCustomer}
                                            >
                                                {LangHelper.getResource('Verify')}
                                            </Button>
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="10" md="10">
                                {
                                    relatedCustomers.length > 0 &&
                                    <div className="verify-customer">
                                        <VerifyCustomer listOfCustomers={relatedCustomers} onClick={this.deleteVerifyInsertCustomer} />
                                    </div>
                                }
                                </Col>
                            </Form.Group>
                            <Form.Group as={Row}>
                                <Col sm="12" md="12">
                                    <Form.Group as={Row}>
                                        <Form.Label column sm="2" md="2" htmlFor="subject">{LangHelper.getResource('Subject')}</Form.Label>
                                        <Col sm="8" md="8">
                                            <AutoComplete isInvalid={touched.subject && errors.subject}
                                                value={values.subject}
                                                options={feedbackSubjectTemplates} displayField="subject"
                                                onChange={value => setFieldValue('subject', value)}
                                                onInputChange={handleGetFeedbackSubjectTemplates}
                                            />
                                        </Col>
                                    </Form.Group>
                                </Col>
                            </Form.Group>
                        </div>
                    </div>
                    <div className="panel-group border-bottom-0">
                        <Form.Group as={Row} className="panel-title" onClick={() => this.handleCollapseExpand('autoGenerated')}
                            aria-controls="collapse-expand-autoGenerated"
                            aria-expanded={!collapse.autoGenerated}
                        >
                            <Form.Label>{LangHelper.getResource('AutoGenerated')}</Form.Label>
                        </Form.Group>
                        <Collapse in={!collapse.autoGenerated}>
                            <div className="panel-content">
                                <Form.Control as="textarea" rows={3} className="shadow-none" name="autoGenerated"
                                    value={values.autoGenerated} onChange={handleChange}
                                />
                            </div>
                        </Collapse>
                    </div>
                    <div className="panel-group border-bottom-0">
                        <Form.Group as={Row} className="panel-title" onClick={() => this.handleCollapseExpand('remark')}
                            aria-controls="collapse-expand-remark"
                            aria-expanded={!collapse.remark}
                        >
                            <Form.Label className="required">{LangHelper.getResource('Remark')}</Form.Label>
                        </Form.Group>
                        <Collapse in={!collapse.remark}>
                            <div id="collapse-expand-remark" className="panel-content">
                                <CkEditor isInvalid={touched.remark && errors.remark}
                                    data={values.remark} username={window.currentUsername}
                                    onChange={value => setFieldValue('remark', value)}
                                />
                            </div>
                        </Collapse>
                    </div>
                    <div className="panel-group border-bottom-0">
                        <Form.Group as={Row} className="panel-title" onClick={() => this.handleCollapseExpand('solution')}
                            aria-controls="collapse-expand-solution"
                            aria-expanded={!collapse.solution}
                        >
                            <Form.Label className="required">{LangHelper.getResource('Solution')}</Form.Label>
                        </Form.Group>
                        <Collapse in={!collapse.solution}>
                            <div id="collapse-expand-solution" className="panel-content">
                                <CkEditor isInvalid={touched.solution && errors.solution}
                                    data={values.solution} username={window.currentUsername}
                                    onChange={value => setFieldValue('solution', value)}
                                />
                            </div>
                        </Collapse>
                    </div>
                </Modal.Body>
                <Modal.Footer>
                    <Button size="sm" type="submit" variant="primary" disabled={isSubmitting}>
                        {LangHelper.getResource('Save')}
                    </Button>
                </Modal.Footer>
            </Form>
        );
    };

    render() {
        const { insertSettings, duplicateFeedbackId } = this.props;
        if (!insertSettings) {
            return null;
        }

        return (
            <Fragment>
                <Modal show className="communication-modal-dialog" dialogAs={DraggableModalDialog}
                    backdrop="static" keyboard={false} size="xl" centered
                    onHide={this.props.onClose}
                >
                    <Modal.Header closeButton>
                        <Modal.Title as="div">{LangHelper.getResource('InsertCommunicationLog')}</Modal.Title>
                    </Modal.Header>
                    <Formik
                        innerRef={el => this.formik = el}
                        initialValues={this.initFormData()}
                        validate={values => validateFormik(values, insertSettings)}
                        onSubmit={this.handleSubmit}
                    >
                        {this.renderForm}
                    </Formik>
                </Modal>
                {
                    this.state.confirmInsertDialog.show &&
                    <SweetModalDialog size="lg"
                        title={LangHelper.getResource('Confirmation')}
                        contents={<div>Are you sure you want to Add or Update the Feedback/Log?</div>}
                        buttons={[
                            <Button variant="primary" size="sm" onClick={this.handleCheckDuplicate}>
                                {LangHelper.getResource('OK')}
                            </Button>,
                            <Button variant="primary" size="sm" onClick={this.handleCloseConfirmInsertDialog}>
                                {LangHelper.getResource('Cancel')}
                            </Button>
                        ]}
                        onClose={this.handleCloseConfirmInsertDialog}
                    />
                }
                {
                    this.state.checkDuplicateDialog.show &&
                    <SweetModalDialog size="lg"
                        title={LangHelper.getResource('Warning')}
                        contents={<div>{`This customer has a similar log with running number ${duplicateFeedbackId}. Do you want to create this log?`}</div>}
                        buttons={[
                            <Button variant="primary" size="sm" onClick={this.handleInsertLog}>
                                {LangHelper.getResource('OK')}
                            </Button>,
                            <Button variant="primary" size="sm" onClick={this.handleCloseCheckDuplicateDialog}>
                                {LangHelper.getResource('Cancel')}
                            </Button>
                        ]}
                        onClose={this.handleCloseCheckDuplicateDialog}
                    />
                }
            </Fragment>
        );
    }
}

const mapDispatchToProps = dispatch => bindActionCreators(ActionCreators, dispatch);

const mapStateToProps = state => {
    const { insertSettings, feedbackSubjectTemplates, duplicateFeedbackId } = state;
    return { insertSettings, feedbackSubjectTemplates, duplicateFeedbackId };
};

export default connect(mapStateToProps, mapDispatchToProps)(InsertCommunicationLog);
