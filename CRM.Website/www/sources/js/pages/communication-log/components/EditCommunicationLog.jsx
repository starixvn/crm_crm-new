import React, { Component } from 'react';
import { Button, Form, Modal } from 'react-bootstrap';
import { Formik } from 'formik';
import DraggableModalDialog from '@jsroot/components/DraggableModalDialog';
import FormikErrorMessage from '@jsroot/components/FormikErrorMessage';
import ResponseMessage from '@jsroot/components/ResponseMessage';
import LangHelper from '@jsroot/common/langHelper';
import DateTimeService from '@jsroot/common/dateTimeService';
import SweetModalDialog from '@jsroot/components/SweetModalDialog';
import Site from '@jsroot/common/site';
import DataService from '@jsroot/common/dataService';
import Contents from './Contents';
import DropdownDetail from './DropdownDetail';
import VerifySection from './VerifySection';
import ConfirmPopup from '@jsroot/components/ConfirmPopup';
import UnderlineButton from '@jsroot/common/underlineButton';
import {
    getProductParams, getCategoryParams, updateAutoGeneratedCustomerPrefix, getSubjectOnChangeCategories, getSubCategories, sortAndReplaceRelatedCust
} from '@jsroot/common/shareScripts';
import {
    validateFormik, handleChangeProduct, handleChangeSubProduct, isValidCustomer
} from '../common.functions';
import { toast } from 'react-toastify';
import WithHotKey from '@jsroot/components/WithHotKey';
import ReminderRating from '../../../components/ReminderRating';

export class EditCommunicationLog extends Component {
    constructor(props) {
        super(props);

        this.state = {
            contents: {
                autoGenerated: '',
                remark: '',
                solution: '',
                isReviewed: false,
                review: '',
                reviewer: '',
                solveDate: new Date()
            },
            verifySection: {
                noInquiries: '',
                customerNameInput: '',
                subject: '',
                rating: 0
            },
            collapse: {
                autoGenerated: false,
                remark: false,
                solution: false
            },
            extensionOptions: [],
            communicationToolOptions: [],
            mainCategoryOptions: [],
            subCategoryOptions: [],
            productOptions: [],
            subProductOptions: [],
            betTypeOptions: [],
            relatedCustomers: [],
            confirmEditDialog: { show: false },
            communicationLog: null,
            settings: null,
            hasReviewFeedbackPermission: false,
            review: null,
            isReviewed: null,
            editResult: null,
            oldReLatedCust: [],
            deleteRelatedCust: [],
            logFeedback: null,
            statusEdit: null,
            isShowEditPopup: false,
            feedbackSubjectTemplates: []
        };
    }

    async componentDidMount() {
        Site.blockUI();
        const urlLogByFeedbackId = Site.resolveClientUrl('CommunicationLog/GetLogByFeedbackId');

        await DataService.getDataAsync(`${urlLogByFeedbackId}?id=${this.props.feedbackId}&modeId=${0}`).then(response => {
            if (!response || !response.data) {
                return;
            }
            this.setState({ logFeedback: response.data });
        }).then(() => Site.unblockUI()).catch(Site.handleAxiosError);

        const { logFeedback } = this.state;
        const logSettings = this.getLogSettings(logFeedback.log, logFeedback.settings);
        const relatedCustomers = logFeedback.log.relatedCustomers.map(customer => {
            return {
                custId: customer.custId,
                val: customer.username,
                isSiteActive: customer.isSiteActive,
                isLicensee: customer.isLicensee,
                isAuthorized: customer.isAuthorized
            };
        });
        const extensionOptions = logFeedback.settings.extensions.map(item => {
            return {
                id: item.id,
                value: item.value,
                checked: logSettings.extensionIds.includes(item.id)
            };
        });
        const communicationToolOptions = logFeedback.settings.communicationTools.map(item => {
            return {
                id: item.id,
                name: item.name,
                checked: logSettings.communicationToolIds.includes(item.id)
            };
        });
        const mainCategoryOptions = logFeedback.settings.mainCategories.map(item => {
            return {
                mainCategoryID: item.mainCategoryID,
                name: item.name,
                checked: logSettings.mainCategoryIds.includes(item.mainCategoryID)
            };
        });

        const mainCategoryIds = logSettings.mainCategoryIds.join(',').split(',');
        const subCategoryIds = logSettings.subCategoryIds.join(',').split(',');
        const subCategoryOptions = getSubCategories(mainCategoryIds, logFeedback.settings.subCategories, subCategoryIds, false);

        const productOptions = logFeedback.settings.products.map(item => {
            return {
                id: item.id,
                value: item.value,
                checked: logSettings.productIds.includes(item.id)
            };
        });
        const subProducts = logFeedback.settings.subProducts.filter(item => logSettings.productIds.includes(item.parentId) && item.parentId !== 0);
        const subProductOptions = subProducts.map(item => {
            return {
                id: item.id,
                value: item.value,
                checked: logSettings.subProductIds.includes(item.id)
            };
        });
        const bettypes = logFeedback.settings.bettypes.filter(item => logSettings.subProductIds.includes(item.parentId) && item.parentId !== 0);
        const betTypeDistinct = bettypes.filter((v, i, a) => a.findIndex(t => t.id === v.id) === i);
        const betTypeOptions = betTypeDistinct.map(item => {
            return {
                id: item.id,
                value: item.value,
                checked: logSettings.betTypeIds.includes(item.id)
            };
        });

        this.setState({
            communicationLog: this.initFormikData(logFeedback.log, logFeedback.settings),
            settings: logFeedback.settings,
            hasReviewFeedbackPermission: logFeedback.hasReviewFeedbackPermission,
            review: logFeedback.log.review,
            isReviewed: logFeedback.log.isReviewed,
            extensionOptions,
            communicationToolOptions,
            mainCategoryOptions,
            subCategoryOptions,
            productOptions,
            subProductOptions,
            betTypeOptions,
            relatedCustomers,
            oldReLatedCust: relatedCustomers
        });
    }

    handleKeyDownFunc = event => {
        if (event.ctrlKey && event.key === 's') {
            event.preventDefault();
            this.formik.submitForm();
        }

        if (event.ctrlKey && event.key === 'e') {
            event.preventDefault();
            this.handleVerifyRelatedCustomer(this.state.verifySection.customerNameInput);
        }
    }

    initFormikData = (log, settings) => {
        const logSettings = this.getLogSettings(log, settings);
        this.setState({
            contents: {
                ...this.state.contents,
                autoGenerated: log.autoField, remark: log.description, solution: log.solution,
                solveDate: DateTimeService.toLongDateTimeFormat(log.solveDate), isReviewed: log.isReviewed,
                review: log.review, reviewer: log.reviewer
            }
        });
        const communicationJoins = logSettings.communicationToolIds.join(',');
        const isExistCommunication = this.state.logFeedback?.settings?.communicationTools?.filter(x => communicationJoins.includes(x.id.toString())).length > 0;
        this.handleChangeVerifySection('subject', log.subject);
        this.handleChangeVerifySection('noInquiries', log.noInquiries > 0 ? log.noInquiries : '');
        this.handleChangeVerifySection('rating', log.rating);
        return {
            feedbackId: log.feedbackId,
            customerId: log.custId,
            customerNameInput: '',
            startTime: new Date(log.feedbackDate),
            endTime: new Date(log.resolutionDate),
            extensionIds: logSettings.extensionIds.join(','),
            communicationToolIds: isExistCommunication ? communicationJoins : '',
            mainCategoryIds: logSettings.mainCategoryIds.join(','),
            subCategoryIds: logSettings.subCategoryIds.join(','),
            productIds: logSettings.productIds.join(','),
            subProductIds: logSettings.subProductIds.join(','),
            betTypeIds: logSettings.betTypeIds.join(','),
            roleId: log.roleId,
            siteId: log.siteId,
            siteName: log.siteSetting.name,
            statusId: log.statusId,
            responseId: log.responseId,
            licenseeTypeId: log.licenseeType,
            countryId: log.countryId,
            languageId: log.languageId,
            subject: '',
            autoGenerated: log.autoField,
            remark: log.description,
            solution: log.solution,
            review: log.review,
            isReviewed: log.isReviewed
        };
    };

    getLogSettings = log => {
        const logSettings = log.settings;
        const extensions = logSettings.filter(item => item.settingType === 'Station');
        const communicationTools = logSettings.filter(item => item.settingType === 'Communication');
        const categories = logSettings.filter(item => item.settingType === 'Category');
        const products = logSettings.filter(item => item.settingType === 'Product');
        return {
            extensionIds: extensions.map(x => x.settingId),
            communicationToolIds: communicationTools.map(x => x.settingId),
            mainCategoryIds: categories.map(x => x.settingId),
            subCategoryIds: categories.map(x => x.subSettingId),
            productIds: products.map(x => x.settingId),
            subProductIds: products.map(x => x.subSettingId),
            betTypeIds: products.map(x => x.subSettingIdLevel3)
        };
    };

    handleChangeVerifySection = (name, value) => {
        this.setState({ verifySection: { ...this.state.verifySection, [name]: value } });
    };

    handleChangeContent = (name, value) => {
        this.setState({ contents: { ...this.state.contents, [name]: value } });
    };

    handleSubmit = (values, { setSubmitting }) => {
        setSubmitting(true);
        const { settings, relatedCustomers, review, isReviewed, contents, verifySection } = this.state;
        const mainCategoryIds = [...new Set(values.mainCategoryIds.split(','))];
        const productIds = values.productIds ? [...new Set(values.productIds.split(','))] : [settings.productNA.id];
        const relatedCustValid = relatedCustomers.filter(item => item.custId !== 0 && item.isAuthorized);
        const replaceAutoGenerated = sortAndReplaceRelatedCust(relatedCustValid, contents.autoGenerated);

        const params = {
            feedbackId: values.feedbackId,
            customerId: values.customerId,
            startTime: DateTimeService.toLongDateTimeFormat(values.startTime),
            endTime: DateTimeService.toLongDateTimeFormat(values.endTime),
            extensionIds: values.extensionIds !== '' ? values.extensionIds : settings.extensionNA.id,
            communicationToolIds: values.communicationToolIds,
            products: getProductParams(productIds.length > 0 ? productIds : [],
                values.subProductIds.length > 0 ? values.subProductIds.split(',') : [],
                values.betTypeIds.length > 0 ? values.betTypeIds.split(',') : [], settings),
            categories: getCategoryParams(mainCategoryIds, values.subCategoryIds.split(','), settings.subCategories),
            relatedCustomerIds: relatedCustomers.length > 0 ? relatedCustValid.filter(i => i.custId !== 0 && i.isAuthorized).map(item => item.custId).join(',') : null,
            responseId: values.responseId,
            languageId: parseInt(values.languageId, 10),
            licenseeTypeId: values.licenseeTypeId,
            siteId: values.siteId,
            statusId: values.statusId,
            roleId: values.roleId,
            countryId: values.countryId,
            noInquiries: verifySection.noInquiries,
            subject: verifySection.subject,
            description: contents.remark,
            autoGenerated: replaceAutoGenerated,
            solution: contents.solution,
            isReviewed: contents.isReviewed,
            review: contents.review,
            updateReviewedMode: this.getUpdateReviewMode(contents, review, isReviewed),
            isDeletedFeedbackView: false,
            rating: parseInt(verifySection.rating, 10)
        };

        this.handleReVerifyInactiveAndConfirm(params, setSubmitting);
    };

    handleReVerifyInactiveAndConfirm = async (params, setSubmitting) => {
        const { relatedCustomers, oldReLatedCust, deleteRelatedCust } = this.state;
        const url = 'CustomerSetting/VerifyUsername';
        const newRelatedCust = relatedCustomers.filter(x => !oldReLatedCust.some(y => y.custId === x.custId));
        const newRelatedCustName = newRelatedCust.map(x => x.val).join(',');
        if (newRelatedCustName.length > 0) {
            await DataService.postDataAsync(url, { username: newRelatedCustName }).then(response => {
                const customerRemains = oldReLatedCust.filter(x => !deleteRelatedCust.some(y => y.custId === x.custId));
                const customers = [...response.data, ...customerRemains];
                this.setState({ relatedCustomers: customers });
                const inactiveCustomers = response.data.filter(customer => !customer.isSiteActive && customer.custId !== 0 && customer.isLicensee);
                if (inactiveCustomers.length > 0) {
                    const inactiveUserName = inactiveCustomers.map(x => x.val).join(',');
                    const message = LangHelper.getResource('ErrorMessageInactiveSiteRelate') + inactiveUserName;
                    this.setState({ editResult: { isSuccessful: false, message } });
                    setSubmitting(false);
                } else {
                    this.setState({ editResult: null });
                    this.confirmEditFeedback(params);
                }
            }).catch(Site.handleAxiosError);
        } else {
            this.setState({ editResult: null });
            this.confirmEditFeedback(params);
        }
    };

    getUpdateReviewMode = (contents, review, isReviewed) => {
        if (review === contents.review && isReviewed === contents.isReviewed) {
            return 0;
        }
        return !contents.isReviewed ? 2 : 1;
    };

    setStateSubProduct = subProducts => {
        this.setState({ subProductOptions: subProducts });
    };

    setStateBetType = betTypes => {
        this.setState({ betTypeOptions: betTypes });
    };

    handleChangeMainCategory = (setFieldValue, categoryIds, subCategoryIds, settings) => {
        const tempSubject = getSubjectOnChangeCategories(categoryIds ? categoryIds.split(',') : [], this.state.verifySection.subject, settings.mainCategories);
        setFieldValue('mainCategoryIds', categoryIds);
        this.handleChangeVerifySection('subject', tempSubject);
        if (categoryIds) {
            const subCategoryId = subCategoryIds.length > 0 ? subCategoryIds.split(',') : [];
            const subCategories = getSubCategories(categoryIds.split(','), settings.subCategories, subCategoryId, false);
            this.setState({ subCategoryOptions: subCategories });
        } else {
            setFieldValue('subCategoryIds', '');
            this.setState({ subCategoryOptions: [] });
        }
    };

    handleVerifyRelatedCustomer = async customerNameInput => {
        const url = 'CustomerSetting/VerifyUsername';
        const customersInput = customerNameInput.trim()
            .replace(/,\s+/g, ',').replace(/^,+|,+$/g, '').replace(/,{2,}/g, ',').replace(/ /g, ',');
        if (customersInput === '') {
            return;
        }
        if (isValidCustomer(customersInput)) {
            await DataService.postDataAsync(url, { username: customersInput }).then(response => {
                let editCustomers = [...this.state.relatedCustomers, ...response.data];
                editCustomers = editCustomers.filter((x, y, z) => z.findIndex(t => t.custId === x.custId && t.val === x.val) === y);
                this.setState({ relatedCustomers: editCustomers });

                const updateAutoGenerated = updateAutoGeneratedCustomerPrefix(true, editCustomers, this.state.contents.autoGenerated);
                this.handleChangeContent('autoGenerated', updateAutoGenerated);
                this.handleChangeVerifySection('customerNameInput', '');
            }).catch(Site.handleAxiosError);
        } else {
            toast.error('The customer name must not be longer than 50 characters!');
        }
    };

    deleteVerifyEditCustomer = idRelatedCustomer => {
        const editRelated = this.state.relatedCustomers.filter(item => item.custId !== idRelatedCustomer);
        const customers = this.state.relatedCustomers.filter(item => item.custId === idRelatedCustomer);
        const deleteRelatedCustCombine = [...this.state.deleteRelatedCust, ...customers];
        this.setState({ relatedCustomers: editRelated, deleteRelatedCust: deleteRelatedCustCombine });

        const updateAutoGenerated = updateAutoGeneratedCustomerPrefix(true, editRelated, this.state.contents.autoGenerated);
        this.handleChangeContent('autoGenerated', updateAutoGenerated);
    };

    handleCollapseExpand = (section = '') => {
        this.setState(prevState => ({
            collapse: { ...prevState.collapse, [section]: !prevState.collapse[section] }
        }));
    };

    confirmEditFeedback = params => {
        this.setState({
            confirmEditDialog: { show: true, params }
        });
    };

    handleCloseConfirmEditDialog = () => {
        this.setState({
            confirmEditDialog: { show: false }
        });
        this.formik.setSubmitting(false);
    };

    handleEditLog = async () => {
        Site.blockUI();
        const url = 'CommunicationLog/EditCommunicationLog';
        const { params } = this.state.confirmEditDialog;
        await DataService.postDataAsync(url, params).then(response => {
            Site.unblockUI();
            this.setState({ editResult: response.data, confirmEditDialog: { show: false } });
            if (response.data.isSuccessful) {
                setTimeout(() => {
                    this.props.onClose(true);
                }, 3000);
            } else {
                this.formik.setSubmitting(false);
            }
        }).catch(Site.handleAxiosError);
    };

    isOldEqualNewIdV1 = () => {
        const { communicationLog } = this.state;
        const { values } = this.formik;
        if (
            communicationLog.responseId !== parseInt(values.responseId, 10) ||
            communicationLog.statusId !== parseInt(values.statusId, 10) ||
            communicationLog.siteId !== values.siteId
        ) {
            return true;
        }
        return false;
    };

    isOldEqualNewIdV2 = () => {
        const { communicationLog } = this.state;
        const { values } = this.formik;
        if (
            communicationLog.languageId !== parseInt(values.languageId, 10) ||
            communicationLog.countryId !== parseInt(values.countryId, 10) ||
            communicationLog.licenseeTypeId !== parseInt(values.licenseeTypeId, 10)
        ) {
            return true;
        }
        return false;
    };

    isOldEqualNewId = () => {
        if (this.isOldEqualNewIdV1() || this.isOldEqualNewIdV2()) {
            return true;
        }
        return false;
    };

    isOldEqualNewValue = () => {
        const { communicationLog, contents } = this.state;
        const { values } = this.formik;
        if (
            communicationLog.isReviewed !== contents.isReviewed ||
            communicationLog.subject !== values.subject
        ) {
            return true;
        }
        return false;
    };

    isOldEqualNewContent = () => {
        const { communicationLog, contents } = this.state;
        if (communicationLog.solution !== contents.solution ||
            communicationLog.review !== contents.review ||
            communicationLog.remark.trim() !== contents.remark.trim()
        ) {
            return true;
        }
        return false;
    };

    onCloseEdit = () => {
        if (this.isOldEqualNewContent() || this.isOldEqualNewId() || this.isOldEqualNewValue()) {
            this.setState({ isShowEditPopup: true });
        } else {
            this.props.onClose(false);
        }
    };

    closeEditConfirm = () => {
        this.setState({ isShowEditPopup: false });
    };

    handleChangeCommunicationTool = (setFieldValue, currentItem, selectedItemsKey) => {
        setFieldValue('communicationToolIds', selectedItemsKey);
    };

    onChangeStartTime = selectedTime => {
        this.formik.setFieldValue('startTime', selectedTime);
    };

    onChangeEndTime = selectedTime => {
        this.formik.setFieldValue('endTime', selectedTime);
    };

    handlePasteCustomer = (event, data) => {
        const customer = data?.trim();
        const item = (event.clipboardData || window.clipboardData).getData('text')
            .replace(/ /g, ',').replace(/\r\n/g, ',').replace(/\n/g, ',').replace(/\t/g, ',')
            .split(',').filter(item => item !== '');
        setTimeout(() => {
            const customerInput = (customer && customer.length > 0 ? customer + ',' : '').concat(item.join(','));
            this.handleChangeVerifySection('customerNameInput', customerInput);
        }, 100);
    };

    handleGetFeedbackSubjectTemplates = Site.debounce(searchText => {
        if (searchText.length >= 2) {
            this.getFeedbackSubjectTemplates(searchText);
        } else {
            this.setState({ feedbackSubjectTemplates: [] });
        }
    });

    getFeedbackSubjectTemplates = async subject => {
        const url = Site.resolveClientUrl('Common/GetFeedbackSubjectTemplate');
        await DataService.getDataAsync(url, { subject }).then(response => {
            this.setState({ feedbackSubjectTemplates: response.data });
        }).catch(Site.handleAxiosError);
    }

    renderForm = ({
        errors,
        values,
        handleChange,
        touched,
        setFieldValue,
        handleSubmit,
        isSubmitting
    }) => {
        const { collapse, contents, editResult, settings, extensionOptions, communicationToolOptions,
            mainCategoryOptions, subCategoryOptions, productOptions, subProductOptions, betTypeOptions,
            relatedCustomers, verifySection } = this.state;
        const hasCreateFeedbackPermission = document.getElementById('hasCreateFeedbackPermission').checked;
        return (
            <Form noValidate onSubmit={handleSubmit}>
                <Modal.Body>
                    <WithHotKey handleKeyDownFunc={this.handleKeyDownFunc} isDocumentHandle />
                    <FormikErrorMessage isSubmitting={isSubmitting} touched={touched} errors={errors} fieldNames={Object.keys(values)} />
                    {
                        editResult &&
                        <ResponseMessage isSuccessful={editResult.isSuccessful}
                            message={editResult.message || LangHelper.getResource('UpdateCommunicationLogSuccessfully')}
                        />
                    }
                    <div className="panel-group border-bottom-0">
                        <div className="panel-content">
                            <DropdownDetail
                                allSettings={settings} {...{ values, errors, touched, setFieldValue, handleChange }}
                                handleChangeSubProduct={handleChangeSubProduct} setStateSubProduct={this.setStateSubProduct} setStateBetType={this.setStateBetType}
                                onChangeStartTime={this.onChangeStartTime} onChangeEndTime={this.onChangeEndTime} handleChangeMainCategory={this.handleChangeMainCategory}
                                handleChangeProduct={handleChangeProduct} handleChangeCommunicationTool={this.handleChangeCommunicationTool}
                                extensions={extensionOptions} communicationTools={communicationToolOptions} mainCategories={mainCategoryOptions} subCategories={subCategoryOptions}
                                products={productOptions} subProducts={subProductOptions} betTypes={betTypeOptions}
                            />
                            <VerifySection
                                handleVerifyCreateRelatedCustomer={this.handleVerifyRelatedCustomer} relatedCustomers={relatedCustomers}
                                deleteVerifyCreateCustomer={this.deleteVerifyEditCustomer} handlePasteCustomer={this.handlePasteCustomer}
                                handleChangeVerifySection={this.handleChangeVerifySection} verifySection={verifySection}
                                feedbackSubjectTemplates={this.state.feedbackSubjectTemplates} handleGetFeedbackSubjectTemplates={this.handleGetFeedbackSubjectTemplates}
                                isValidSubject={touched.subject && errors.subject} isValidCustomerInput={touched.customerNameInput && errors.customerNameInput}
                            />
                        </div>
                    </div>
                    <Contents
                        handleCollapseExpand={this.handleCollapseExpand}
                        handleChangeContent={this.handleChangeContent}
                        isEdit contents={contents} collapse={collapse}
                        isInValidRemark={touched.remark && errors.remark}
                        isInValidSolution={touched.solution && errors.solution}
                        isInValidReview={touched.review && errors.review}
                    />
                </Modal.Body >
                <Modal.Footer>
                    {
                        hasCreateFeedbackPermission && (
                            <Button size="sm" type="submit" variant="primary" disabled={isSubmitting}>
                                <UnderlineButton.saveButton />
                            </Button>
                        )
                    }
                </Modal.Footer>
            </Form>
        );
    };

    render() {
        const { communicationLog, settings, confirmEditDialog, isShowEditPopup, contents, verifySection } = this.state;
        if (communicationLog === null || settings === null) {
            return null;
        }

        return (
            <div>
                <Modal show className="communication-modal-dialog" dialogAs={DraggableModalDialog}
                    backdrop="static" keyboard={false} centered onHide={this.onCloseEdit}
                >
                    <Modal.Header closeButton>
                        <Modal.Title as="div">{LangHelper.getResource('EditCommunicationLog')}</Modal.Title>
                    </Modal.Header>
                    <Formik
                        innerRef={el => this.formik = el}
                        initialValues={communicationLog}
                        validate={values => validateFormik(values, contents, verifySection, settings)}
                        onSubmit={this.handleSubmit}
                    >
                        {this.renderForm}
                    </Formik>
                    {
                        isShowEditPopup &&
                        <ConfirmPopup
                            onClose={this.closeEditConfirm}
                            onSubmit={() => this.props.onClose(false)}
                            size='md'
                            content={
                                <div>
                                    <div>{LangHelper.formatString(LangHelper.getResource('ThereAreSomeChangesOnInput'), 'communication')}</div>
                                    <div>{LangHelper.getResource('ConfirmIgnoreTheseChanges')}</div>
                                </div>
                            }
                            title={LangHelper.getResource('ConfirmIgnoreChanges')}
                        />
                    }
                </Modal>
                {
                    confirmEditDialog.show &&
                    <SweetModalDialog size="lg"
                        title={LangHelper.getResource('Confirmation')}
                        contents={
                            <>
                                <ReminderRating value={verifySection.rating}/>
                                <div>Are you sure you want to Add or Update the Feedback/Log?</div>
                            </>
                        }
                        buttons={[
                            <Button variant="primary" size="sm" onClick={this.handleEditLog}>
                                {LangHelper.getResource('OK')}
                            </Button>,
                            <Button variant="primary" size="sm" onClick={this.handleCloseConfirmEditDialog}>
                                {LangHelper.getResource('Cancel')}
                            </Button>
                        ]}
                        onClose={this.handleCloseConfirmEditDialog}
                    />
                }
            </div>
        );
    }
}

export default EditCommunicationLog;