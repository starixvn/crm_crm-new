import React, { Fragment, PureComponent } from 'react';
import { Form,  Row, Collapse } from 'react-bootstrap';
import LangHelper from '@jsroot/common/langHelper';
import CkEditor from '@jsroot/components/ckeditor/index';

export default class Contents extends PureComponent {
    render() {
        const currentUsername = window.currentUsername;
        const { handleChangeContent, contents, isInValidRemark, isInValidSolution, isInValidReview, collapse, handleCollapseExpand, isEdit } = this.props;
        return (
            <Fragment>
                <div className="panel-group border-bottom-0">
                    <Form.Group as={Row} className="panel-title"
                        aria-expanded={!collapse.autoGenerated}
                        aria-controls="collapse-expand-autoGenerated"
                        onClick={() => handleCollapseExpand('autoGenerated')}
                    >
                        <Form.Label>{LangHelper.getResource('AutoGenerated')}</Form.Label>
                    </Form.Group>
                    <Collapse in={!collapse.autoGenerated} >
                        <div className="panel-content">
                            <Form.Control as="textarea" className="shadow-none"
                                rows={3} name="autoGenerated"
                                value={contents.autoGenerated}
                                onChange={event => handleChangeContent('autoGenerated', event.target.value)}
                            />
                        </div>
                    </Collapse>
                </div>
                <div className="panel-group border-bottom-0">
                    <Form.Group as={Row} className="panel-title"
                        aria-expanded={!collapse.remark}
                        aria-controls="collapse-expand-remark"
                        onClick={() => handleCollapseExpand('remark')}
                    >
                        <Form.Label className="required">{LangHelper.getResource('Remark')}</Form.Label>
                    </Form.Group>
                    <Collapse in={!collapse.remark}>
                        <div className="panel-content" id="collapse-expand-remark">
                            <CkEditor data={contents.remark} username={currentUsername}
                                isInvalid={isInValidRemark}
                                onChange={value => handleChangeContent('remark', value)}
                            />
                        </div>
                    </Collapse>
                </div>
                <div className={`panel-group ${isEdit ? 'border-bottom-0' : ''}`} >
                    <Form.Group as={Row} className="panel-title"
                        aria-expanded={!collapse.solution}
                        aria-controls="collapse-expand-solution"
                        onClick={() => handleCollapseExpand('solution')}
                    >
                        <Form.Label className="required">{LangHelper.getResource('Solution')}</Form.Label>
                    </Form.Group>
                    <Collapse in={!collapse.solution}>
                        <div className="panel-content" id="collapse-expand-solution">
                            <CkEditor data={contents.solution} username={currentUsername}
                                isInvalid={isInValidSolution}
                                onChange={value => handleChangeContent('solution', value)}
                            />
                        </div>
                    </Collapse>
                </div>
                {
                    isEdit && (
                        <div className="panel-group">
                            <Form.Group as={Row} className="panel-title">
                                <Form.Label className={contents.isReviewed ? 'required' : ''}>
                                    {LangHelper.getResource('Review')}
                                </Form.Label>
                                <input className="ml-2" type='checkbox' checked={contents.isReviewed}
                                    onChange={event => handleChangeContent('isReviewed', event.target.checked)}
                                />
                                <span className="font-italic ml-2">
                                    {contents.reviewer ? LangHelper.formatString(LangHelper.getResource('ReviewerBy'), contents.reviewer, contents.solveDate) : ''}
                                </span>
                            </Form.Group>
                            <Collapse in={contents.isReviewed}>
                                <div className="panel-content">
                                    <CkEditor data={contents.review} username={currentUsername}
                                        isInvalid={isInValidReview}
                                        onChange={value => handleChangeContent('review', value)}
                                    />
                                </div>
                            </Collapse>
                        </div>
                    )
                }
            </Fragment>
        );
    }
}