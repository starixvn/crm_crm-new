import React from 'react';
import Contents from '../Contents'
import { Form } from 'react-bootstrap';
import CkEditor from '@jsroot/components/ckeditor/index';
import { shallow } from 'enzyme';

describe('Contents', () => {
    afterAll(() => {
        jest.clearAllMocks();
    });

    describe('renderCollapse', () => {
        const props = {
            contents:{
                autoGenerated: '',
                remark: '',
                solution: '',
                isReviewed: false,
                reviewer: '',
                solveDate: new Date('2022-01-01')
            },
            collapse:{
                autoGenerated: false,
                remark: false,
                solution: false
            },
            handleChangeContent: jest.fn(),
            isEdit: true,
            handleCollapseExpand: jest.fn()
        };

        it.each([
            0,
            1,
            2
          ])("should call exact function when collapse at", number => {
            // Arrange
            const container = shallow(<Contents {...props} />);

            // Act
            container.find(Form.Group).at(number).simulate('click');
            container.find(Form.Group).at(number).simulate('click');
            container.find(Form.Group).at(number).simulate('click');

            // Assert
            expect(props.handleCollapseExpand).toHaveBeenCalled();
        });

        it('handleChange should call exact function when autoGenerated changed', () => {
            // Arrange
            const container = shallow(<Contents {...props} />);
            container.find(Form.Control).at(0).simulate('change', {target:{value: 'test'}});

            // Act
            expect(props.handleChangeContent).toHaveBeenCalledWith('autoGenerated', 'test');
        });

        it('handleChange should call exact function when remark changed', () => {
            // Arrange
            // Act
            const container = shallow(<Contents {...props} />);
            container.find(CkEditor).at(0).simulate('change', 'value');
            
            // Assert
            expect(props.handleChangeContent).toHaveBeenCalledWith('remark','value');
        });

        it('handleChange should call exact function when solution changed', () => {
            // Arrange

            // Act
            const container = shallow(<Contents {...props} />);
            container.find(CkEditor).at(1).simulate('change', 'value');
            
            // Assert
            expect(props.handleChangeContent).toHaveBeenCalledWith('solution','value');
        });

        it('handleChange should call exact function when isReviewed render check', () => {
            // Arrange
            const event = { 
                target: {checked: true}
            }; 
            // Act
            const container = shallow(<Contents {...props} />);
            container.find('input').at(0).simulate('change', event);
            
            // Assert
            expect(props.handleChangeContent).toHaveBeenCalledWith('isReviewed', true);
        });

        it('handleChange should call exact function when review changed', () => {
            // Act
            const container = shallow(<Contents {...props} />);
            container.find(CkEditor).at(2).simulate('change', 'value');
            
            // Assert
            expect(props.handleChangeContent).toHaveBeenCalledWith('review', 'value');
        });
    });
});