    using Xunit;

    public class EditCustomerNewManualFeedbackCommandTests
    {
        [Fact]
        public void GetSettingKey_WhenCalled_ReturnExpectedSettingKey()
        {
            // Arrange
            var criteria = new EditCustomerNewManualFeedbackCommand();
            var expected = "Acc_CRM_NewManualFeedback_FeedbackUpd";

            // Act
            var actual = criteria.GetSettingKey();

            // Assert
            Assert.Equal(expected, actual);
        }

        [Theory]
        [InlineData(0,"", 0)]
        public void IsValid_ManualFeedbackIsInvalid_ReturnFalse(int feedbackID, string communicationToolIds, int languageID)
        {
            // Arrange
            var criteria = new EditCustomerNewManualFeedbackCommand
            {
                FeedbackID = feedbackID,
                CommunicationToolIds = communicationToolIds,
                LanguageID = languageID,
                Categories = null
            };

            // Act
            var actual = criteria.IsValid();

            // Assert
            Assert.False(actual);
        }

        [Fact]
        public void IsValid_ManualFeedbackIsValid_ReturnTrue()
        {
            // Arrange
            var criteria = new EditCustomerNewManualFeedbackCommand
            {
                FeedbackID = 1,
                TitleID = 1,
                UserID = 1,
                CountryID = 1,
                FirstName = "FirstName",
                LastName = "LastName",
                SiteID = 1,
                Subject = "Subject",
                CommunicationToolIds = "1",
                RelatedCustomerIds = "1",
                Birthday = new DateTime(),
                FeedbackDate = new DateTime(),
                ResolutionDate = new DateTime(),
                LanguageID = 1,
                ExtensionIds = "1",
                RoleID = 1,
                Products = new List<ProductSubProductBettypeSetting> { new() { ProductId = 1} },
                Categories = new List<CategorySubCategorySetting>(){ new() { MainCategoryId = 1, SubCategoryId = 1 } },
                ResponseID = 1,
                StatusID = 1,
                Description = "Description",
                AutoGenerated = "AutoGenerated",
                Solution = "Solution",
                UpdateReviewedMode = 1,
                IsReviewed = true,
                IsOverwrite = true,
                Review = "Review",
                ReviewerId = 1,
                RefCode1 = "RefCode1",
                RefCode2 = "RefCode2",
                Passport = "Passport",
                LicenseeTypeId = 1,
                CustID = 1,
                IP = "1",
                NoInquiries = 1,
                IsDeletedFeedbackView = true,
                CommunicationInfos = new List<NewCommunicationTool> { new() { CommunicationID = 1 } }
            };

